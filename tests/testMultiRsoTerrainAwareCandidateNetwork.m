            moonRadius, ...
            theta0, ...
            moonAngularRate);

    [objectFinalStates, ...
        objectFinalCovariances, ...
        objectFinalInnovations] = ...
        estimation.lunarSurfaceEkf( ...
            commonReferenceTime, ...
            observationTimes, ...
            rightAscension, ...
            declination, ...
            sensorLatitudes, ...
            sensorLongitudes, ...
            dem, ...
            measurementAvailable, ...
            fixedInitialStates(:,objectIndex), ...
            fixedInitialCovariances(:,:,objectIndex), ...
            measurementCovariance, ...
            accelerationNoiseIntensity, ...
            moonMu, ...
            moonRadius, ...
            theta0, ...
            moonAngularRate);

    finalStateHistories{objectIndex} = objectFinalStates;
    finalCovarianceHistories{objectIndex} = ...
        objectFinalCovariances;
    finalInnovationHistories{objectIndex} = ...
        objectFinalInnovations;

    assert(any(all(isfinite( ...
        finalInnovationHistories{objectIndex}),1)), ...
        "The final EKF performed no updates for object %d.",objectIndex);

    numberOfSelectedSensors = length(finalSensorIndices);

    posteriorIndices = ...
        numberOfSelectedSensors : ...
        numberOfSelectedSensors : ...
        length(observationTimes);

    posteriorStates = ...
        finalStateHistories{objectIndex}(:,posteriorIndices);

    posteriorCovariances = ...
        finalCovarianceHistories{objectIndex}(:,:,posteriorIndices);

    stateError = posteriorStates - objectTruthHistory;

    positionErrorNorms(objectIndex,:) = ...
        vecnorm(stateError(1:3,:),2,1);

    velocityErrorNorms(objectIndex,:) = ...
        vecnorm(stateError(4:6,:),2,1);

    for timeIndex = 1:numberOfOptimizationTimes
        covariance = posteriorCovariances(:,:,timeIndex);
        covariance = 0.5*(covariance + covariance.');

        positionThreeSigmaNorms(objectIndex,timeIndex) = ...
            3*sqrt(trace(covariance(1:3,1:3)));

        velocityThreeSigmaNorms(objectIndex,timeIndex) = ...
            3*sqrt(trace(covariance(4:6,4:6)));
    end
end

