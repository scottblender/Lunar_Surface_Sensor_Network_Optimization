for objectIndex = 1:numberOfObjects
    objectTruthHistory = reshape( ...
        truthOptimizationHistories(:,:,objectIndex), ...
        6,numberOfOptimizationTimes);

    objectTruthAvailability = reshape( ...
        truthOptimizationAvailability(:,:,objectIndex), ...
        numberOfCandidates,numberOfOptimizationTimes);

