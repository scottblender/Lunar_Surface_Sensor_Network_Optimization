%% testMultiRsoTerrainAwareCandidateNetwork
% End-to-end terrain-aware network test for multiple independent RSOs.
%
% Workflow:
%   1. Propagate truth trajectories for every RSO.
%   2. Build one sensor/DEM terrain-horizon database.
%   3. Perform one representative, terrain-gated IOD for each RSO.
%   4. Propagate every IOD state and P0 to a common reference epoch.
%   5. Hold those RSO-specific priors fixed during network evaluation.
%   6. Build candidate-dependent Jacobian and terrain-LOS databases.
%   7. Evaluate coverage and EKF D-optimality for candidate networks.
%   8. Run one final state-updating EKF per RSO with the selected network.

clear;
close all;
clc;

rng(11,"twister");

%% Project paths and required functions

testDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(testDirectory);
sourceDirectory = fullfile(projectRoot,"src");

assert(isfolder(sourceDirectory), ...
    "Source directory not found: %s",sourceDirectory);

addpath(sourceDirectory);
rehash path;

requiredFunctions = [
    "orbitDynamics.propagateLunarOrbit"
    "orbitDynamics.lunarStateAndStmDynamics"
    "referenceFrames.moonRotating"
    "referenceFrames.topographic"
    "measurements.surfaceRaDecMeasurement"
    "measurements.surfaceRaDecJacobian"
    "iod.anglesOnlyIod"
    "estimation.isotropicProcessNoise"
    "estimation.propagateNetworkCovariance"
    "estimation.lunarSurfaceEkf"
    "optimization.precomputeTrackingData"
    "optimization.buildTerrainAwareLosDatabase"
    "optimization.informationObjective"
    "optimization.coverageObjective"
    "digitalElevationModel.buildMaximumTerrainHorizonDatabase"
    "lsqnonlin"
];

for functionIndex = 1:length(requiredFunctions)
    functionName = requiredFunctions(functionIndex);

    assert(~isempty(which(functionName)), ...
        "%s was not found.",functionName);
end

%% Load the DEM and convert its angular grid to radians

demPath = fullfile( ...
    projectRoot,"data","new_lunar_interpolant_model.mat");

if ~isfile(demPath)
    demPath = fullfile( ...
        testDirectory,"new_lunar_interpolant_model.mat");
end

assert(isfile(demPath),"DEM file was not found.");

demData = load(demPath,"F");

assert(isfield(demData,"F"), ...
    "DEM file must contain a variable named F.");

sourceDem = demData.F;

latitudeGrid = deg2rad(sourceDem.GridVectors{1}(:));
longitudeGrid = deg2rad(sourceDem.GridVectors{2}(:));
elevationGrid = sourceDem.Values;

if longitudeGrid(end) < 2*pi
    longitudeGrid = [longitudeGrid;2*pi];
    elevationGrid = [elevationGrid,elevationGrid(:,1)];
end

dem = griddedInterpolant( ...
    {latitudeGrid,longitudeGrid}, ...
    elevationGrid,"linear","nearest");

%% Constants and estimation settings

moonRadius = 1737.4;                 % km
moonMu = 4902.800066;                % km^3/s^2
moonAngularRate = 2*pi/(27.321661*86400);
theta0 = 0;

minimumElevation = deg2rad(0);
horizonMargin = deg2rad(0);

rightAscensionSigma = deg2rad(1/3600);
declinationSigma = deg2rad(1/3600);

measurementCovariance = diag([ ...
    rightAscensionSigma^2
    declinationSigma^2
]);

measurementNoiseFactor = ...
    chol(measurementCovariance,"lower");

accelerationNoiseIntensity = 1e-15; % km^2/s^3

stateScales = [1;1;1;1e-3;1e-3;1e-3];

%% Candidate surface sensors
% A small, deliberately varied set is used so this remains a test rather
% than a production-scale optimization.

candidateNames = [
    "Candidate 1"
    "Candidate 2"
    "Candidate 3"
    "Candidate 4"
];

candidateLatitudes = deg2rad([ ...
    -84.000000
    -89.505332
    -76.149000
    -76.000000
]);

candidateLongitudes = deg2rad([ ...
     37.000000
    102.857143
    115.200000
    300.000000
]);

numberOfCandidates = length(candidateLatitudes);

measurementCovariances = repmat( ...
    measurementCovariance,1,1,numberOfCandidates);

%% Build the terrain database once for the candidate sensors

maximumTerrainRange = 100;           % km
terrainRangeStep = 0.5;              % km
horizonAzimuthStep = deg2rad(1);     % rad

[horizonAzimuths, ...
    maximumTerrainElevation, ...
    maximumFeatureRange, ...
    sensorElevations, ...
    maximumFeatureElevations] = ...
    digitalElevationModel.buildMaximumTerrainHorizonDatabase( ...
        candidateLatitudes, ...
        candidateLongitudes, ...
        dem, ...
        maximumTerrainRange, ...
        terrainRangeStep, ...
        horizonAzimuthStep, ...
        moonRadius);

assert(all(isfinite(maximumTerrainElevation),"all"), ...
    "The terrain-horizon database contains nonfinite angles.");

%% Define the RSO set

rsoNames = [
    "LRO-like 50 km polar"
    "Chandrayaan-1-like 100 km polar"
    "200 km, 60 deg inclined"
];

numberOfObjects = length(rsoNames);

truthInitialStates = zeros(6,numberOfObjects);

truthInitialStates(:,1) = circularOrbitState( ...
    moonRadius + 50,deg2rad(90),deg2rad(37),0,moonMu);

truthInitialStates(:,2) = circularOrbitState( ...
    moonRadius + 100,deg2rad(90),deg2rad(120),deg2rad(35),moonMu);

% This orientation places a low southern pass near the south-polar
% candidate longitudes early in the test arc.
truthInitialStates(:,3) = circularOrbitState( ...
    moonRadius + 200,deg2rad(60),deg2rad(205.2),deg2rad(-90),moonMu);

objectWeights = ones(numberOfObjects,1);

%% Propagate all truth trajectories on the same time grid

outputStep = 30;                     % s
finalTime = 8*3600;                  % s
times = (0:outputStep:finalTime).';

numberOfTimes = length(times);
truthStateHistories = zeros(6,numberOfTimes,numberOfObjects);

for objectIndex = 1:numberOfObjects
    [propagatedTimes,propagatedStates] = ...
        orbitDynamics.propagateLunarOrbit( ...
            truthInitialStates(:,objectIndex), ...
            times, ...
            moonMu=moonMu);

    assert(max(abs(propagatedTimes - times)) < 1e-9, ...
        "The propagated time grid changed for object %d.",objectIndex);

    truthStateHistories(:,:,objectIndex) = propagatedStates.';
end

%% Terrain-aware truth visibility for all sensors and RSOs

[truthTerrainAvailability, ...
    truthAzimuths, ...
    truthElevations, ...
    truthRanges, ...
    truthLimitingElevations] = ...
    optimization.buildTerrainAwareLosDatabase( ...
        times, ...
        truthStateHistories, ...
        candidateLatitudes, ...
        candidateLongitudes, ...
        dem, ...
        horizonAzimuths, ...
        maximumTerrainElevation, ...
        minimumElevation, ...
        horizonMargin, ...
        moonRadius, ...
        theta0, ...
        moonAngularRate);

truthGeometricAvailability = ...
    truthElevations >= minimumElevation;

assert(all( ...
    truthTerrainAvailability <= truthGeometricAvailability, ...
    "all"), ...
    "Terrain-aware LOS cannot exceed geometric LOS.");

assert(all(any(truthTerrainAvailability,[1,2]),"all"), ...
    "At least one RSO has no terrain-approved observations.");

%% One representative terrain-gated IOD for each RSO
% Each object receives its own fixed state and covariance. The IOD sensor
% may differ by object because IOD geometry is object/sensor dependent.

desiredIodObservationCount = 15;
numberOfMonteCarloSamples = 50;
iodSearchEndTime = 0.40*finalTime;

iodStates = zeros(6,numberOfObjects);
iodCovariances = zeros(6,6,numberOfObjects);
iodReferenceTimes = zeros(numberOfObjects,1);
iodSensorIndices = zeros(numberOfObjects,1);
iodObservationCounts = zeros(numberOfObjects,1);
iodDiagnostics = cell(numberOfObjects,1);

for objectIndex = 1:numberOfObjects
    objectAvailability = reshape( ...
        truthTerrainAvailability(:,:,objectIndex), ...
        numberOfCandidates,numberOfTimes);

    [iodSensorIndices(objectIndex),acquisitionIndices] = ...
        selectRepresentativeIodPass( ...
            objectAvailability, ...
            times, ...
            iodSearchEndTime, ...
            desiredIodObservationCount);

    iodObservationCounts(objectIndex) = length(acquisitionIndices);

    sensorIndex = iodSensorIndices(objectIndex);

    [observerPositionsMci,rightAscension,declination] = ...
        simulateSingleSensorMeasurements( ...
            times, ...
            truthStateHistories(:,:,objectIndex), ...
            sensorIndex, ...
            candidateLatitudes, ...
            candidateLongitudes, ...
            dem, ...
            objectAvailability(sensorIndex,:).', ...
            measurementNoiseFactor, ...
            moonRadius, ...
            theta0, ...
            moonAngularRate);

    [iodState,iodCovariance,iodReferenceTime,objectIodDiagnostics] = ...
        iod.anglesOnlyIod( ...
            times, ...
            rightAscension, ...
            declination, ...
            observerPositionsMci, ...
            acquisitionIndices, ...
            measurementCovariance, ...
            numberOfMonteCarloSamples, ...
            100 + objectIndex, ...
            moonMu);

    iodStates(:,objectIndex) = iodState;
    iodCovariances(:,:,objectIndex) = iodCovariance;
    iodReferenceTimes(objectIndex) = iodReferenceTime;
    iodDiagnostics{objectIndex} = objectIodDiagnostics;

    iodCovariances(:,:,objectIndex) = 0.5*( ...
        iodCovariances(:,:,objectIndex) + ...
        iodCovariances(:,:,objectIndex).');

    [~,positiveDefiniteFlag] = chol( ...
        iodCovariances(:,:,objectIndex),"lower");

    assert(positiveDefiniteFlag == 0, ...
        "IOD covariance is not positive definite for object %d.", ...
        objectIndex);
end

%% Move all fixed IOD priors to one common optimization epoch
% The latest IOD reference epoch is used. Earlier priors are propagated to
% that epoch once, before any candidate network is evaluated.

commonReferenceTime = max(iodReferenceTimes);

fixedInitialStates = zeros(6,numberOfObjects);
fixedInitialCovariances = zeros(6,6,numberOfObjects);

for objectIndex = 1:numberOfObjects
    [commonEpochState,commonEpochCovariance] = ...
        propagatePriorToTime( ...
            iodReferenceTimes(objectIndex), ...
            commonReferenceTime, ...
            iodStates(:,objectIndex), ...
            iodCovariances(:,:,objectIndex), ...
            accelerationNoiseIntensity, ...
            moonMu);

    fixedInitialStates(:,objectIndex) = commonEpochState;
    fixedInitialCovariances(:,:,objectIndex) = ...
        commonEpochCovariance;
end

optimizationIndices = find(times > commonReferenceTime);
optimizationTimes = times(optimizationIndices);
numberOfOptimizationTimes = length(optimizationTimes);

assert(numberOfOptimizationTimes > 0, ...
    "No optimization arc remains after the IOD stage.");

truthOptimizationHistories = ...
    truthStateHistories(:,optimizationIndices,:);

%% Precompute candidate-dependent tracking data for every RSO

referenceStateHistories = ...
    zeros(6,numberOfOptimizationTimes,numberOfObjects);

stateTransitionHistories = ...
    zeros(6,6,numberOfOptimizationTimes,numberOfObjects);

processNoiseHistories = ...
    zeros(6,6,numberOfOptimizationTimes,numberOfObjects);

measurementJacobianHistories = ...
    zeros(2,6,numberOfCandidates, ...
    numberOfOptimizationTimes,numberOfObjects);

geometricAvailabilityDatabase = ...
    false(numberOfCandidates, ...
    numberOfOptimizationTimes,numberOfObjects);

for objectIndex = 1:numberOfObjects
    [objectReferenceStates, ...
        objectStateTransitions, ...
        objectProcessNoise, ...
        objectMeasurementJacobians, ...
        objectGeometricAvailability] = ...
        optimization.precomputeTrackingData( ...
            commonReferenceTime, ...
            optimizationTimes, ...
            fixedInitialStates(:,objectIndex), ...
            candidateLatitudes, ...
            candidateLongitudes, ...
            dem, ...
            minimumElevation, ...
            accelerationNoiseIntensity, ...
            moonMu, ...
            moonRadius, ...
            theta0, ...
            moonAngularRate);

    referenceStateHistories(:,:,objectIndex) = ...
        objectReferenceStates;

    stateTransitionHistories(:,:,:,objectIndex) = ...
        objectStateTransitions;

    processNoiseHistories(:,:,:,objectIndex) = ...
        objectProcessNoise;

    measurementJacobianHistories(:,:,:,:,objectIndex) = ...
        objectMeasurementJacobians;

    geometricAvailabilityDatabase(:,:,objectIndex) = ...
        objectGeometricAvailability;
end

%% Apply the reusable terrain horizon to each nominal RSO trajectory

[terrainAvailabilityDatabase, ...
    nominalAzimuths, ...
    nominalElevations, ...
    nominalRanges, ...
    nominalLimitingElevations] = ...
    optimization.buildTerrainAwareLosDatabase( ...
        optimizationTimes, ...
        referenceStateHistories, ...
        candidateLatitudes, ...
        candidateLongitudes, ...
        dem, ...
        horizonAzimuths, ...
        maximumTerrainElevation, ...
        minimumElevation, ...
        horizonMargin, ...
        moonRadius, ...
        theta0, ...
