%% Local functions

function state = circularOrbitState( ...
    orbitRadius,inclination,raan,trueAnomaly,moonMu)

rotationZ = [ ...
     cos(raan),-sin(raan),0
     sin(raan), cos(raan),0
     0,0,1
];

rotationX = [ ...
    1,0,0
    0,cos(inclination),-sin(inclination)
    0,sin(inclination), cos(inclination)
];

perifocalPosition = orbitRadius*[ ...
    cos(trueAnomaly)
    sin(trueAnomaly)
    0
];

circularSpeed = sqrt(moonMu/orbitRadius);

perifocalVelocity = circularSpeed*[ ...
    -sin(trueAnomaly)
     cos(trueAnomaly)
     0
];

rotation = rotationZ*rotationX;

state = [ ...
    rotation*perifocalPosition
    rotation*perifocalVelocity
];

end

function [sensorIndex,acquisitionIndices] = ...
    selectRepresentativeIodPass( ...
        availability,times,searchEndTime,desiredCount)

numberOfSensors = size(availability,1);
bestRun = zeros(0,1);
sensorIndex = NaN;

for candidateIndex = 1:numberOfSensors
    eligible = availability(candidateIndex,:) & ...
        (times.' <= searchEndTime);

    changes = diff([false,eligible,false]);
    runStarts = find(changes == 1);
    runEnds = find(changes == -1) - 1;

    for runIndex = 1:length(runStarts)
        currentRun = (runStarts(runIndex):runEnds(runIndex)).';

        if length(currentRun) > length(bestRun)
            bestRun = currentRun;
            sensorIndex = candidateIndex;
        end
    end
end

assert(length(bestRun) >= 3, ...
    "No candidate has three terrain-approved IOD observations.");

numberToUse = min(desiredCount,length(bestRun));

selectionLocations = unique(round(linspace( ...
    1,length(bestRun),numberToUse)));

acquisitionIndices = bestRun(selectionLocations);
acquisitionIndices = acquisitionIndices(:);

end

function [observerPositionsMci,rightAscension,declination] = ...
    simulateSingleSensorMeasurements( ...
        times,truthStateHistory,sensorIndex, ...
        candidateLatitudes,candidateLongitudes,dem, ...
        measurementAvailable,measurementNoiseFactor, ...
        moonRadius,theta0,angularRate)

numberOfTimes = length(times);
sensorLatitude = candidateLatitudes(sensorIndex);
sensorLongitude = mod(candidateLongitudes(sensorIndex),2*pi);

observerPositionsMci = zeros(numberOfTimes,3);
rightAscension = NaN(numberOfTimes,1);
declination = NaN(numberOfTimes,1);

sensorMoonRotatingState = referenceFrames.topographic( ...
    zeros(6,1), ...
    sensorLatitude, ...
    sensorLongitude, ...
    dem, ...
    moonRadius, ...
    "toRotating");

for timeIndex = 1:numberOfTimes
    observationTime = times(timeIndex);

    sensorMciState = referenceFrames.moonRotating( ...
        sensorMoonRotatingState, ...
        observationTime, ...
        theta0, ...
        angularRate, ...
        "toInertial");

    observerPositionsMci(timeIndex,:) = sensorMciState(1:3).';

    if ~measurementAvailable(timeIndex)
        continue
    end

    idealMeasurement = measurements.surfaceRaDecMeasurement( ...
        truthStateHistory(:,timeIndex), ...
        observationTime, ...
        sensorLatitude, ...
        sensorLongitude, ...
        dem, ...
        moonRadius, ...
        theta0, ...
        angularRate);

    noisyMeasurement = idealMeasurement + ...
        measurementNoiseFactor*randn(2,1);

    rightAscension(timeIndex) = wrapAngle(noisyMeasurement(1));
    declination(timeIndex) = noisyMeasurement(2);
end

end

function [propagatedState,propagatedCovariance] = ...
    propagatePriorToTime( ...
        initialTime,finalTime,initialState,initialCovariance, ...
        accelerationNoiseIntensity,moonMu)

if abs(finalTime - initialTime) < 1e-12
    propagatedState = initialState;
    propagatedCovariance = initialCovariance;
    return
end

augmentedInitialState = [initialState;reshape(eye(6),36,1)];

odeOptions = odeset("RelTol",1e-11,"AbsTol",1e-12);

[~,augmentedHistory] = ode45( ...
    @(time,augmentedState) ...
        orbitDynamics.lunarStateAndStmDynamics( ...
            time,augmentedState,moonMu), ...
    [initialTime,finalTime], ...
    augmentedInitialState, ...
    odeOptions);

augmentedFinalState = augmentedHistory(end,:).';
propagatedState = augmentedFinalState(1:6);
stateTransitionMatrix = reshape(augmentedFinalState(7:end),6,6);

processNoise = estimation.isotropicProcessNoise( ...
    finalTime - initialTime, ...
    accelerationNoiseIntensity);

propagatedCovariance = ...
    stateTransitionMatrix*initialCovariance* ...
    stateTransitionMatrix.' + processNoise;

propagatedCovariance = 0.5*( ...
    propagatedCovariance + propagatedCovariance.');

end

function [observationTimes,rightAscension,declination, ...
    sensorLatitudes,sensorLongitudes,measurementAvailable] = ...
    simulateSelectedNetwork( ...
        times,truthStateHistory,selectedSensorIndices, ...
        candidateLatitudes,candidateLongitudes,dem, ...
        terrainAvailability,measurementNoiseFactor, ...
        moonRadius,theta0,angularRate)

numberOfTimes = length(times);
numberOfSelectedSensors = length(selectedSensorIndices);
numberOfObservations = numberOfTimes*numberOfSelectedSensors;

observationTimes = zeros(numberOfObservations,1);
rightAscension = NaN(numberOfObservations,1);
declination = NaN(numberOfObservations,1);
sensorLatitudes = zeros(numberOfObservations,1);
sensorLongitudes = zeros(numberOfObservations,1);
measurementAvailable = false(numberOfObservations,1);

observationIndex = 0;

for timeIndex = 1:numberOfTimes
    for selectedIndex = 1:numberOfSelectedSensors
        observationIndex = observationIndex + 1;
        sensorIndex = selectedSensorIndices(selectedIndex);

        sensorLatitude = candidateLatitudes(sensorIndex);
        sensorLongitude = mod(candidateLongitudes(sensorIndex),2*pi);

        observationTimes(observationIndex) = times(timeIndex);
        sensorLatitudes(observationIndex) = sensorLatitude;
        sensorLongitudes(observationIndex) = sensorLongitude;

        measurementAvailable(observationIndex) = ...
            terrainAvailability(sensorIndex,timeIndex);

        if ~measurementAvailable(observationIndex)
            continue
        end

        idealMeasurement = measurements.surfaceRaDecMeasurement( ...
            truthStateHistory(:,timeIndex), ...
            times(timeIndex), ...
            sensorLatitude, ...
            sensorLongitude, ...
            dem, ...
            moonRadius, ...
            theta0, ...
            angularRate);

        noisyMeasurement = idealMeasurement + ...
            measurementNoiseFactor*randn(2,1);

        rightAscension(observationIndex) = ...
            wrapAngle(noisyMeasurement(1));

        declination(observationIndex) = noisyMeasurement(2);
    end
end

end

function wrappedAngle = wrapAngle(angle)

wrappedAngle = atan2(sin(angle),cos(angle));

end
