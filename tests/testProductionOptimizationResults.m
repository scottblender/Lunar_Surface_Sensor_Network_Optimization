function report = testProductionOptimizationResults(userConfig)
% TESTPRODUCTIONOPTIMIZATIONRESULTS Verify the completed production campaign.
%
% This test discovers the newest complete 6000-FE, 20-run production study
% for each requested network-size/objective case, loads every individual
% run_###.mat result, re-processes the saved sensor network with the frozen
% optimization database, and verifies that the stored results are internally
% consistent and reproducible.
%
% Default production definition:
%   network sizes:  [3 5 7 10]
%   objectives:     information, coverage
%   runs/case:      20
%   FE/run:         6000
%   population:     60
%   seeds/case:     1000:1019
%
% The test checks, for every individual result file:
%   - required run fields and configuration metadata;
%   - run index and optimizer seed sequence;
%   - exact FE completion and monotonic best-so-far convergence;
%   - valid, unique, in-range, canonical sensor indices;
%   - stored sensor coordinates/table against the frozen candidate database;
%   - a fresh optimization.networkObjective evaluation of the saved network;
%   - stored objective, information, coverage, and per-RSO diagnostics;
%   - final-population dimensions and finite scores;
%   - consistency between each individual run file and study_summary.mat.
%
% It also verifies each study-level summary and the complete campaign count.
% With the defaults, exactly 8 study summaries and 160 run files are required.
%
% Usage
%   report = testProductionOptimizationResults;
%
% Optional overrides
%   config = struct();
%   config.maximumCampaignSpanHours = 168;
%   report = testProductionOptimizationResults(config);
%
% The function throws an assertion at the first failed verification. If it
% returns normally, report.allChecksPassed is true.

arguments
    userConfig (1,1) struct = struct()
end

%% ========================================================================
%  Project paths and configuration
%  ========================================================================

thisFile = mfilename("fullpath");
testDirectory = fileparts(thisFile);
projectRoot = fileparts(testDirectory);
sourceDirectory = fullfile(projectRoot,"src");
resultsDirectory = fullfile(projectRoot,"results");

assert(isfolder(sourceDirectory), ...
    "Source directory not found: %s",sourceDirectory);

addpath(sourceDirectory);
rehash path;

defaultConfig = struct();
defaultConfig.resultsDirectory = resultsDirectory;
defaultConfig.databaseFile = fullfile(resultsDirectory,"optimization_database.mat");
defaultConfig.networkSizes = [3 5 7 10];
defaultConfig.objectiveModes = ["information","coverage"];
defaultConfig.numberOfRuns = 20;
defaultConfig.functionEvaluationBudget = 6000;
defaultConfig.populationSize = 60;
defaultConfig.baseSeed = 1000;
defaultConfig.studyName = "lunar_surface_production_optimization";
defaultConfig.requireParallel = true;
defaultConfig.relativeTolerance = 1e-10;
defaultConfig.coordinateToleranceRad = 1e-12;
defaultConfig.maximumCampaignSpanHours = 168;

config = mergeStruct(defaultConfig,userConfig);
config.resultsDirectory = string(config.resultsDirectory);
config.databaseFile = string(config.databaseFile);
config.networkSizes = double(config.networkSizes(:).');
config.objectiveModes = lower(string(config.objectiveModes(:).'));
config.studyName = string(config.studyName);

validateattributes(config.networkSizes,{'numeric'}, ...
    {'vector','integer','positive','nonempty'});
validateattributes(config.numberOfRuns,{'numeric'}, ...
    {'scalar','integer','positive'});
validateattributes(config.functionEvaluationBudget,{'numeric'}, ...
    {'scalar','integer','positive'});
validateattributes(config.populationSize,{'numeric'}, ...
    {'scalar','integer','>=',2});
validateattributes(config.baseSeed,{'numeric'}, ...
    {'scalar','integer','nonnegative'});
validateattributes(config.relativeTolerance,{'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(config.coordinateToleranceRad,{'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(config.maximumCampaignSpanHours,{'numeric'}, ...
    {'scalar','real','positive'});
assert(islogical(config.requireParallel) && isscalar(config.requireParallel), ...
    "requireParallel must be a scalar logical.");
assert(all(ismember(config.objectiveModes,["information","coverage"])), ...
    "objectiveModes may contain only information and coverage.");
assert(mod(config.functionEvaluationBudget,config.populationSize) == 0, ...
    "functionEvaluationBudget must be divisible by populationSize.");

%% ========================================================================
%  Load frozen database
%  ========================================================================

assert(isfile(config.databaseFile), ...
    "Frozen optimization database was not found: %s",config.databaseFile);

databaseData = load(config.databaseFile,"database");
assert(isfield(databaseData,"database"), ...
    "optimization_database.mat does not contain database.");
database = databaseData.database;

numberOfCandidates = database.meta.numberOfCandidates;
numberOfObjects = database.meta.numberOfObjects;

%% ========================================================================
%  Expected production cases
%  ========================================================================

numberOfNetworkSizes = numel(config.networkSizes);
numberOfObjectiveModes = numel(config.objectiveModes);
numberOfCases = numberOfNetworkSizes*numberOfObjectiveModes;

caseNetworkSize = zeros(numberOfCases,1);
caseObjectiveMode = strings(numberOfCases,1);
caseCounter = 0;

for networkIndex = 1:numberOfNetworkSizes
    for objectiveIndex = 1:numberOfObjectiveModes
        caseCounter = caseCounter + 1;
        caseNetworkSize(caseCounter) = config.networkSizes(networkIndex);
        caseObjectiveMode(caseCounter) = config.objectiveModes(objectiveIndex);
    end
end

runRoot = fullfile(config.resultsDirectory,"optimization_runs");
assert(isfolder(runRoot), ...
    "Optimization result directory was not found: %s",runRoot);

[summaryFiles,campaignTimes] = resolveStudySummaries( ...
    runRoot,caseNetworkSize,caseObjectiveMode,config);

if all(~isnat(campaignTimes))
    assert(all(diff(campaignTimes) > seconds(0)), ...
        ["Selected production studies are not in the expected batch order. " ...
         "This usually means result directories from different launches " ...
         "were mixed."]);

    campaignSpanHours = hours(max(campaignTimes)-min(campaignTimes));
    assert(campaignSpanHours <= config.maximumCampaignSpanHours, ...
        ["Selected production studies span %.2f hours, exceeding the " ...
         "allowed %.2f-hour campaign window. Results may come from " ...
         "different launches."], ...
        campaignSpanHours,config.maximumCampaignSpanHours);
else
    campaignSpanHours = NaN;
end

%% ========================================================================
%  Allocate run and case reports
%  ========================================================================

expectedTotalRuns = numberOfCases*config.numberOfRuns;

runCase = zeros(expectedTotalRuns,1);
runNetworkSize = zeros(expectedTotalRuns,1);
runObjectiveMode = strings(expectedTotalRuns,1);
runIndexColumn = zeros(expectedTotalRuns,1);
seedColumn = zeros(expectedTotalRuns,1);
sensorIndicesColumn = cell(expectedTotalRuns,1);
savedObjectiveColumn = zeros(expectedTotalRuns,1);
recomputedObjectiveColumn = zeros(expectedTotalRuns,1);
informationScoreColumn = zeros(expectedTotalRuns,1);
coverageScoreColumn = zeros(expectedTotalRuns,1);
runtimeSecondsColumn = zeros(expectedTotalRuns,1);
parallelRetryCountColumn = zeros(expectedTotalRuns,1);
resultFileColumn = strings(expectedTotalRuns,1);

caseBestRun = zeros(numberOfCases,1);
caseBestObjective = zeros(numberOfCases,1);
caseInformationScore = zeros(numberOfCases,1);
caseCoverageScore = zeros(numberOfCases,1);
caseMeanObjective = zeros(numberOfCases,1);
caseStdObjective = zeros(numberOfCases,1);
caseMeanRuntimeSeconds = zeros(numberOfCases,1);
caseParallelRetries = zeros(numberOfCases,1);

runCounter = 0;

fprintf("\n");
fprintf("============================================================\n");
fprintf("Production optimization result verification\n");
fprintf("============================================================\n");
fprintf("Database:            %s\n",config.databaseFile);
fprintf("Cases:               %d\n",numberOfCases);
fprintf("Runs per case:       %d\n",config.numberOfRuns);
fprintf("Expected run files:  %d\n",expectedTotalRuns);
fprintf("FE per run:          %d\n",config.functionEvaluationBudget);
fprintf("\n");

%% ========================================================================
%  Process every study and every individual result file
%  ========================================================================

for caseIndex = 1:numberOfCases
    summaryFile = summaryFiles(caseIndex);
    studyDirectory = string(fileparts(summaryFile));

    summaryData = load(summaryFile,"studyState");
    assert(isfield(summaryData,"studyState"), ...
        "Study summary does not contain studyState: %s",summaryFile);
    studyState = summaryData.studyState;

    expectedNetworkSize = caseNetworkSize(caseIndex);
    expectedObjectiveMode = caseObjectiveMode(caseIndex);

    verifyStudyConfiguration( ...
        studyState,expectedNetworkSize,expectedObjectiveMode,config);

    runFiles = dir(fullfile(studyDirectory,"run_*.mat"));
    assert(numel(runFiles) == config.numberOfRuns, ...
        ["Case %d (%s, N=%d) contains %d run files; expected %d. " ...
         "Study directory: %s"], ...
        caseIndex,expectedObjectiveMode,expectedNetworkSize, ...
        numel(runFiles),config.numberOfRuns,studyDirectory);

    assert(numel(studyState.runStates) == config.numberOfRuns, ...
        "studyState.runStates has the wrong length for %s.",studyDirectory);

    savedObjectives = zeros(config.numberOfRuns,1);
    savedRunTimes = zeros(config.numberOfRuns,1);
    savedRetryCounts = zeros(config.numberOfRuns,1);

    fprintf("Case %d/%d: N=%d | %s\n", ...
        caseIndex,numberOfCases,expectedNetworkSize,expectedObjectiveMode);
    fprintf("  %s\n",studyDirectory);

    for runIndex = 1:config.numberOfRuns
        runFile = fullfile(studyDirectory,sprintf("run_%03d.mat",runIndex));
        assert(isfile(runFile), ...
            "Missing expected result file: %s",runFile);

        runData = load(runFile,"runState");
        assert(isfield(runData,"runState"), ...
            "Result file does not contain runState: %s",runFile);
        runState = runData.runState;

        verifyRunStateBasics( ...
            runState,runIndex,expectedNetworkSize,expectedObjectiveMode, ...
            numberOfCandidates,numberOfObjects,config,runFile);

        sensorIndices = double(runState.bestSensorIndices(:));

        %% Candidate-coordinate and table verification

        expectedLatitudesRad = ...
            double(database.candidates.latitudesRad(sensorIndices));
        expectedLongitudesRad = ...
            double(database.candidates.longitudesRad(sensorIndices));

        assertAbsoluteEqual( ...
            runState.bestSensorLatitudesRad(:),expectedLatitudesRad(:), ...
            config.coordinateToleranceRad, ...
            sprintf("Stored sensor latitudes disagree with database in %s",runFile));

        assertAbsoluteEqual( ...
            runState.bestSensorLongitudesRad(:),expectedLongitudesRad(:), ...
            config.coordinateToleranceRad, ...
            sprintf("Stored sensor longitudes disagree with database in %s",runFile));

        verifySensorTable( ...
            runState.bestSensorTable,sensorIndices, ...
            expectedLatitudesRad,expectedLongitudesRad, ...
            config.coordinateToleranceRad,runFile);

        %% Fresh objective re-evaluation of the saved sensor network

        [recomputedObjective,recomputedDetails] = ...
            optimization.networkObjective( ...
                sensorIndices,database,expectedObjectiveMode);

        assert(recomputedDetails.feasible, ...
            "Saved network was classified as infeasible when reprocessed: %s", ...
            runFile);

        assertRelativeEqual( ...
            runState.bestObjective,recomputedObjective, ...
            config.relativeTolerance, ...
            sprintf("Saved objective does not reproduce in %s",runFile));

        assertRelativeEqual( ...
            runState.bestInformationScore,recomputedDetails.informationScore, ...
            config.relativeTolerance, ...
            sprintf("Information score does not reproduce in %s",runFile));

        assertRelativeEqual( ...
            runState.bestCoverageScore,recomputedDetails.coverageScore, ...
            config.relativeTolerance, ...
            sprintf("Coverage score does not reproduce in %s",runFile));

        assertRelativeEqual( ...
            runState.informationByObject(:), ...
            recomputedDetails.informationByObject(:), ...
            config.relativeTolerance, ...
            sprintf("Per-RSO information results do not reproduce in %s",runFile));

        assertRelativeEqual( ...
            runState.coverageByObject(:), ...
            recomputedDetails.coverageByObject(:), ...
            config.relativeTolerance, ...
            sprintf("Per-RSO coverage results do not reproduce in %s",runFile));

        %% Individual-file versus study-summary consistency

        summaryRunState = studyState.runStates{runIndex};
        assert(summaryRunState.runIndex == runState.runIndex, ...
            "Run index differs between individual file and study summary.");
        assert(summaryRunState.seed == runState.seed, ...
            "Seed differs between individual file and study summary.");
        assert(isequal(summaryRunState.bestSensorIndices(:),sensorIndices(:)), ...
            "Sensor indices differ between individual file and study summary.");
        assertRelativeEqual( ...
            summaryRunState.bestObjective,runState.bestObjective, ...
            config.relativeTolerance, ...
            "Objective differs between individual file and study summary.");
        assert(isequal(summaryRunState.history.fe(:),runState.history.fe(:)), ...
            "FE history differs between individual file and study summary.");
        assertRelativeEqual( ...
            summaryRunState.history.bestJ(:),runState.history.bestJ(:), ...
            config.relativeTolerance, ...
            "Convergence history differs between individual file and study summary.");

        savedObjectives(runIndex) = runState.bestObjective;
        savedRunTimes(runIndex) = runState.runtimeSeconds;
        savedRetryCounts(runIndex) = runState.parallelRetryCount;

        runCounter = runCounter + 1;
        runCase(runCounter) = caseIndex;
        runNetworkSize(runCounter) = expectedNetworkSize;
        runObjectiveMode(runCounter) = expectedObjectiveMode;
        runIndexColumn(runCounter) = runIndex;
        seedColumn(runCounter) = runState.seed;
        sensorIndicesColumn{runCounter} = sensorIndices(:).';
        savedObjectiveColumn(runCounter) = runState.bestObjective;
        recomputedObjectiveColumn(runCounter) = recomputedObjective;
        informationScoreColumn(runCounter) = runState.bestInformationScore;
        coverageScoreColumn(runCounter) = runState.bestCoverageScore;
        runtimeSecondsColumn(runCounter) = runState.runtimeSeconds;
        parallelRetryCountColumn(runCounter) = runState.parallelRetryCount;
        resultFileColumn(runCounter) = string(runFile);

        fprintf("  Run %02d/%02d verified | seed %d | J = %.12g\n", ...
            runIndex,config.numberOfRuns,runState.seed,runState.bestObjective);
    end

    %% Study-level aggregate verification

    assertRelativeEqual( ...
        studyState.bestObjectives(:),savedObjectives, ...
        config.relativeTolerance, ...
        sprintf("studyState.bestObjectives is inconsistent for case %d",caseIndex));

    assertRelativeEqual( ...
        studyState.runTimesSeconds(:),savedRunTimes, ...
        config.relativeTolerance, ...
        sprintf("studyState.runTimesSeconds is inconsistent for case %d",caseIndex));

    assertRelativeEqual( ...
        studyState.meanBestObjective,mean(savedObjectives), ...
        config.relativeTolerance, ...
        sprintf("Mean objective is inconsistent for case %d",caseIndex));

    assertRelativeEqual( ...
        studyState.stdBestObjective,std(savedObjectives), ...
        config.relativeTolerance, ...
        sprintf("Objective standard deviation is inconsistent for case %d",caseIndex));

    assertRelativeEqual( ...
        studyState.meanRuntimeSeconds,mean(savedRunTimes), ...
        config.relativeTolerance, ...
        sprintf("Mean runtime is inconsistent for case %d",caseIndex));

    assertRelativeEqual( ...
        studyState.stdRuntimeSeconds,std(savedRunTimes), ...
        config.relativeTolerance, ...
        sprintf("Runtime standard deviation is inconsistent for case %d",caseIndex));

    [expectedBestObjective,expectedBestRunIndex] = min(savedObjectives);
    expectedBestRunState = studyState.runStates{expectedBestRunIndex};

    assert(studyState.overallBestRunIndex == expectedBestRunIndex, ...
        "overallBestRunIndex is inconsistent for case %d.",caseIndex);

    assertRelativeEqual( ...
        studyState.overallBestObjective,expectedBestObjective, ...
        config.relativeTolerance, ...
        sprintf("overallBestObjective is inconsistent for case %d",caseIndex));

    assert(isequal( ...
        studyState.overallBestSensorIndices(:), ...
        expectedBestRunState.bestSensorIndices(:)), ...
        "overallBestSensorIndices is inconsistent for case %d.",caseIndex);

    assertRelativeEqual( ...
        studyState.overallBestInformationScore, ...
        expectedBestRunState.bestInformationScore, ...
        config.relativeTolerance, ...
        sprintf("Overall-best information score is inconsistent for case %d",caseIndex));

    assertRelativeEqual( ...
        studyState.overallBestCoverageScore, ...
        expectedBestRunState.bestCoverageScore, ...
        config.relativeTolerance, ...
        sprintf("Overall-best coverage score is inconsistent for case %d",caseIndex));

    assert(isequal(studyState.parallelRetryCounts(:),savedRetryCounts(:)), ...
        "Parallel retry counts are inconsistent for case %d.",caseIndex);

    caseBestRun(caseIndex) = expectedBestRunIndex;
    caseBestObjective(caseIndex) = expectedBestObjective;
    caseInformationScore(caseIndex) = ...
        expectedBestRunState.bestInformationScore;
    caseCoverageScore(caseIndex) = ...
        expectedBestRunState.bestCoverageScore;
    caseMeanObjective(caseIndex) = mean(savedObjectives);
    caseStdObjective(caseIndex) = std(savedObjectives);
    caseMeanRuntimeSeconds(caseIndex) = mean(savedRunTimes);
    caseParallelRetries(caseIndex) = sum(savedRetryCounts);

    fprintf("  Case verified: %d/%d run files complete.\n\n", ...
        config.numberOfRuns,config.numberOfRuns);
end

assert(runCounter == expectedTotalRuns, ...
    "Processed %d run files; expected %d.",runCounter,expectedTotalRuns);

%% ========================================================================
%  Build returned verification report
%  ========================================================================

runTable = table( ...
    runCase, ...
    runNetworkSize, ...
    runObjectiveMode, ...
    runIndexColumn, ...
    seedColumn, ...
    sensorIndicesColumn, ...
    savedObjectiveColumn, ...
    recomputedObjectiveColumn, ...
    informationScoreColumn, ...
    coverageScoreColumn, ...
    runtimeSecondsColumn, ...
    parallelRetryCountColumn, ...
    resultFileColumn, ...
    'VariableNames',{ ...
        'Case', ...
        'NetworkSize', ...
        'ObjectiveMode', ...
        'RunIndex', ...
        'Seed', ...
        'SensorIndices', ...
        'SavedObjective', ...
        'RecomputedObjective', ...
        'InformationScore', ...
        'CoverageScore', ...
        'RuntimeSeconds', ...
        'ParallelRetryCount', ...
        'ResultFile'});

caseTable = table( ...
    (1:numberOfCases).', ...
    caseNetworkSize, ...
    caseObjectiveMode, ...
    summaryFiles, ...
    caseBestRun, ...
    caseBestObjective, ...
    caseInformationScore, ...
    caseCoverageScore, ...
    caseMeanObjective, ...
    caseStdObjective, ...
    caseMeanRuntimeSeconds, ...
    caseParallelRetries, ...
    'VariableNames',{ ...
        'Case', ...
        'NetworkSize', ...
        'ObjectiveMode', ...
        'StudySummaryFile', ...
        'BestRun', ...
        'BestObjective', ...
        'BestInformationScore', ...
        'BestCoverageScore', ...
        'MeanObjective', ...
        'StdObjective', ...
        'MeanRuntimeSeconds', ...
        'ParallelRetries'});

report = struct();
report.version = "production_optimization_result_verification_v1";
report.created = string(datetime("now"));
report.databaseFile = config.databaseFile;
report.configuration = config;
report.numberOfCases = numberOfCases;
report.numberOfRunFiles = runCounter;
report.expectedNumberOfRunFiles = expectedTotalRuns;
report.campaignSpanHours = campaignSpanHours;
report.studySummaryFiles = summaryFiles;
report.caseTable = caseTable;
report.runTable = runTable;
report.allChecksPassed = true;

fprintf("============================================================\n");
fprintf("Production result verification PASSED\n");
fprintf("============================================================\n");
fprintf("Study summaries verified: %d\n",numberOfCases);
if isfinite(campaignSpanHours)
    fprintf("Campaign span:            %.2f hr\n",campaignSpanHours);
end
fprintf("Run files verified:       %d\n",runCounter);
fprintf("Sensor networks replayed: %d\n",runCounter);
fprintf("Expected run files:       %d\n",expectedTotalRuns);
fprintf("Total parallel retries:   %d\n",sum(parallelRetryCountColumn));
fprintf("\nCase summary:\n");
disp(caseTable);
fprintf("All production optimization results were generated consistently.\n");

end

