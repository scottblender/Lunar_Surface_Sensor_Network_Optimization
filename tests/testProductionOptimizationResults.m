function [summaryFiles,campaignTimes] = resolveStudySummaries( ...
    runRoot,caseNetworkSize,caseObjectiveMode,config)

allSummaryFiles = dir(fullfile(runRoot,"*","study_summary.mat"));
assert(~isempty(allSummaryFiles), ...
    "No study_summary.mat files were found under %s.",runRoot);

[~,sortOrder] = sort([allSummaryFiles.datenum],"descend");
allSummaryFiles = allSummaryFiles(sortOrder);

numberOfCases = numel(caseNetworkSize);
summaryFiles = strings(numberOfCases,1);
campaignTimes = NaT(numberOfCases,1);

for caseIndex = 1:numberOfCases
    expectedNetworkSize = caseNetworkSize(caseIndex);
    expectedObjectiveMode = caseObjectiveMode(caseIndex);
    matchFound = false;

    for fileIndex = 1:numel(allSummaryFiles)
        candidateFile = string(fullfile( ...
            allSummaryFiles(fileIndex).folder,allSummaryFiles(fileIndex).name));

        candidateData = load(candidateFile,"studyState");
        if ~isfield(candidateData,"studyState")
            continue
        end

        candidateStudy = candidateData.studyState;

        if ~matchesStudyConfiguration( ...
                candidateStudy,expectedNetworkSize,expectedObjectiveMode,config)
            continue
        end

        candidateDirectory = string(fileparts(candidateFile));
        complete = true;
        for runIndex = 1:config.numberOfRuns
            if ~isfile(fullfile( ...
                    candidateDirectory,sprintf("run_%03d.mat",runIndex)))
                complete = false;
                break
            end
        end

        if ~complete
            continue
        end

        summaryFiles(caseIndex) = candidateFile;
        [~,folderName] = fileparts(candidateDirectory);
        campaignTimes(caseIndex) = extractStudyTimestamp(folderName);
        matchFound = true;
        break
    end

    assert(matchFound, ...
        ["Could not find a complete production study for N=%d, %s. " ...
         "Expected %d runs, %d FE/run, population %d, base seed %d."], ...
        expectedNetworkSize,expectedObjectiveMode,config.numberOfRuns, ...
        config.functionEvaluationBudget,config.populationSize,config.baseSeed);
end

assert(numel(unique(summaryFiles)) == numberOfCases, ...
    "The same study summary was selected for more than one production case.");

end

function tf = matchesStudyConfiguration( ...
    studyState,expectedNetworkSize,expectedObjectiveMode,config)

tf = isstruct(studyState) && isscalar(studyState) && ...
    isfield(studyState,"config") && ...
    isfield(studyState,"numberOfRuns");

if ~tf
    return
end

studyConfig = studyState.config;
requiredConfigFields = { ...
    'networkSize', ...
    'objectiveMode', ...
    'functionEvaluationBudget', ...
    'populationSize', ...
    'baseSeed', ...
    'studyName'};

for fieldIndex = 1:numel(requiredConfigFields)
    if ~isfield(studyConfig,requiredConfigFields{fieldIndex})
        tf = false;
        return
    end
end

tf = ...
    studyState.numberOfRuns == config.numberOfRuns && ...
    studyConfig.networkSize == expectedNetworkSize && ...
    lower(string(studyConfig.objectiveMode)) == expectedObjectiveMode && ...
    studyConfig.functionEvaluationBudget == config.functionEvaluationBudget && ...
    studyConfig.populationSize == config.populationSize && ...
    studyConfig.baseSeed == config.baseSeed && ...
    string(studyConfig.studyName) == config.studyName;

end

function verifyStudyConfiguration( ...
    studyState,expectedNetworkSize,expectedObjectiveMode,config)

assert(matchesStudyConfiguration( ...
    studyState,expectedNetworkSize,expectedObjectiveMode,config), ...
    "Study summary configuration does not match the expected production case.");

requiredFields = [ ...
    "runStates", ...
    "bestObjectives", ...
    "runTimesSeconds", ...
    "meanBestObjective", ...
    "stdBestObjective", ...
    "meanRuntimeSeconds", ...
    "stdRuntimeSeconds", ...
    "overallBestRunIndex", ...
    "overallBestObjective", ...
    "overallBestSensorIndices", ...
    "overallBestInformationScore", ...
    "overallBestCoverageScore", ...
    "parallelRetryCounts"];

requireFields(studyState,requiredFields,"studyState");

end

function verifyRunStateBasics( ...
    runState,runIndex,networkSize,objectiveMode, ...
    numberOfCandidates,numberOfObjects,config,runFile)

requiredFields = [ ...
    "runIndex", ...
    "seed", ...
    "optimizer", ...
    "objectiveMode", ...
    "networkSize", ...
    "numberOfCandidates", ...
    "numberOfObjects", ...
    "functionEvaluationBudget", ...
    "populationSize", ...
    "searchFunctionEvaluations", ...
    "bestSensorIndices", ...
    "bestSensorLatitudesRad", ...
    "bestSensorLongitudesRad", ...
    "bestSensorTable", ...
    "bestObjective", ...
    "bestInformationScore", ...
    "bestCoverageScore", ...
    "informationByObject", ...
    "coverageByObject", ...
    "runtimeSeconds", ...
    "exitFlag", ...
    "finalPopulation", ...
    "finalScores", ...
    "usedParallel", ...
    "parallelRetryCount", ...
    "parallelPoolRestarted", ...
    "history", ...
    "config"];

requireFields(runState,requiredFields,sprintf("runState in %s",runFile));

assert(runState.runIndex == runIndex, ...
    "Unexpected run index in %s.",runFile);
assert(runState.seed == config.baseSeed + runIndex - 1, ...
    "Unexpected optimizer seed in %s.",runFile);
assert(upper(string(runState.optimizer)) == "GA", ...
    "Unexpected optimizer in %s.",runFile);
assert(lower(string(runState.objectiveMode)) == objectiveMode, ...
    "Unexpected objective mode in %s.",runFile);
assert(runState.networkSize == networkSize, ...
    "Unexpected network size in %s.",runFile);
assert(runState.numberOfCandidates == numberOfCandidates, ...
    "Candidate count does not match frozen database in %s.",runFile);
assert(runState.numberOfObjects == numberOfObjects, ...
    "RSO count does not match frozen database in %s.",runFile);
assert(runState.functionEvaluationBudget == config.functionEvaluationBudget, ...
    "Unexpected FE budget in %s.",runFile);
assert(runState.populationSize == config.populationSize, ...
    "Unexpected GA population size in %s.",runFile);
assert(runState.searchFunctionEvaluations == config.functionEvaluationBudget, ...
    "Search did not reach the requested FE budget in %s.",runFile);

sensorIndices = double(runState.bestSensorIndices(:));
assert(numel(sensorIndices) == networkSize, ...
    "Wrong number of saved sensors in %s.",runFile);
assert(all(isfinite(sensorIndices)), ...
    "Sensor indices contain nonfinite values in %s.",runFile);
assert(all(sensorIndices == round(sensorIndices)), ...
    "Sensor indices contain nonintegers in %s.",runFile);
assert(all(sensorIndices >= 1 & sensorIndices <= numberOfCandidates), ...
    "Sensor indices are outside the candidate range in %s.",runFile);
assert(numel(unique(sensorIndices)) == networkSize, ...
    "Duplicate sensor indices were saved in %s.",runFile);
assert(all(diff(sensorIndices) > 0), ...
    "Sensor indices are not stored in canonical increasing order in %s.",runFile);

assert(isfinite(runState.bestObjective), ...
    "Best objective is nonfinite in %s.",runFile);
assert(isfinite(runState.bestInformationScore), ...
    "Information score is nonfinite in %s.",runFile);
assert(isfinite(runState.bestCoverageScore), ...
    "Coverage score is nonfinite in %s.",runFile);
assert(numel(runState.informationByObject) == numberOfObjects && ...
    all(isfinite(runState.informationByObject),"all"), ...
    "Per-RSO information results are invalid in %s.",runFile);
assert(numel(runState.coverageByObject) == numberOfObjects && ...
    all(isfinite(runState.coverageByObject),"all"), ...
    "Per-RSO coverage results are invalid in %s.",runFile);
assert(isfinite(runState.runtimeSeconds) && runState.runtimeSeconds > 0, ...
    "Runtime is invalid in %s.",runFile);

if config.requireParallel
    assert(logical(runState.usedParallel), ...
        "Production run was not marked as parallel in %s.",runFile);
end

assert(isscalar(runState.parallelRetryCount) && ...
    ismember(runState.parallelRetryCount,[0 1]), ...
    "Unexpected parallel retry count in %s.",runFile);
assert(logical(runState.parallelPoolRestarted) == ...
    (runState.parallelRetryCount > 0), ...
    "Parallel restart metadata is inconsistent in %s.",runFile);

requireFields(runState.history,["fe","bestJ","generation"], ...
    sprintf("history in %s",runFile));

historyFe = double(runState.history.fe(:));
historyBestJ = double(runState.history.bestJ(:));
historyGeneration = double(runState.history.generation(:));

assert(~isempty(historyFe), ...
    "FE history is empty in %s.",runFile);
assert(numel(historyFe) == numel(historyBestJ) && ...
    numel(historyFe) == numel(historyGeneration), ...
    "Convergence-history arrays have inconsistent lengths in %s.",runFile);
assert(all(isfinite(historyFe)) && all(isfinite(historyBestJ)) && ...
    all(isfinite(historyGeneration)), ...
    "Convergence history contains nonfinite values in %s.",runFile);
assert(historyFe(end) == config.functionEvaluationBudget, ...
    "Convergence history does not end at the requested FE budget in %s.",runFile);
assert(all(diff(historyFe) > 0), ...
    "FE history is not strictly increasing in %s.",runFile);
assert(all(diff(historyGeneration) >= 0), ...
    "Generation history is not monotonic in %s.",runFile);
assert(all(diff(historyBestJ) <= ...
    config.relativeTolerance*max(1,max(abs(historyBestJ)))), ...
    "Best-so-far objective is not monotonic in %s.",runFile);
assertRelativeEqual( ...
    historyBestJ(end),runState.bestObjective,config.relativeTolerance, ...
    sprintf("Final convergence value differs from saved best objective in %s",runFile));

assert(size(runState.finalPopulation,1) == config.populationSize && ...
    size(runState.finalPopulation,2) == networkSize, ...
    "Final GA population has unexpected dimensions in %s.",runFile);
assert(numel(runState.finalScores) == config.populationSize && ...
    all(isfinite(runState.finalScores),"all"), ...
    "Final GA scores are invalid in %s.",runFile);

if isfield(runState,"solverFinalBestObjective") && ...
        isfinite(runState.solverFinalBestObjective)
    scale = max([1,abs(runState.bestObjective), ...
        abs(runState.solverFinalBestObjective)]);
    assert(runState.bestObjective <= runState.solverFinalBestObjective + ...
        config.relativeTolerance*scale, ...
        "Saved incumbent is worse than solver final best in %s.",runFile);
end

end

