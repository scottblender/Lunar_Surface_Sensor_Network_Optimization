function requireFields(inputStruct,fieldNames,context)

for fieldIndex = 1:numel(fieldNames)
    fieldName = char(fieldNames(fieldIndex));
    assert(isfield(inputStruct,fieldName), ...
        "%s is missing required field %s.",context,fieldName);
end

end

function assertRelativeEqual(actual,expected,tolerance,message)

actual = double(actual(:));
expected = double(expected(:));

assert(numel(actual) == numel(expected), ...
    "%s Array sizes differ.",message);
assert(all(isfinite(actual)) && all(isfinite(expected)), ...
    "%s Values must be finite.",message);

scale = max([1;abs(actual);abs(expected)]);
maximumDifference = max(abs(actual-expected),[],"all");

assert(maximumDifference <= tolerance*scale, ...
    "%s Maximum difference %.6e exceeds tolerance %.6e.", ...
    message,maximumDifference,tolerance*scale);

end

function assertAbsoluteEqual(actual,expected,tolerance,message)

actual = double(actual(:));
expected = double(expected(:));

assert(numel(actual) == numel(expected), ...
    "%s Array sizes differ.",message);
assert(all(isfinite(actual)) && all(isfinite(expected)), ...
    "%s Values must be finite.",message);

maximumDifference = max(abs(actual-expected),[],"all");
assert(maximumDifference <= tolerance, ...
    "%s Maximum difference %.6e exceeds tolerance %.6e.", ...
    message,maximumDifference,tolerance);

end

function timestamp = extractStudyTimestamp(folderName)

folderName = string(folderName);
tokens = regexp(folderName,"_(\d{8}_\d{6})$","tokens","once");

if isempty(tokens)
    timestamp = NaT;
else
    timestamp = datetime(string(tokens{1}), ...
        "InputFormat","yyyyMMdd_HHmmss");
end

end

