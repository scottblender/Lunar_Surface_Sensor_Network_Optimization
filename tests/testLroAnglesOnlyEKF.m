grid on;
xlabel("Time (hr)");
ylabel("-log(det(\bar{P}))");
title("Posterior EKF D-Optimality");

figureTitle = sprintf( ...
    "LRO-like %.0f km Orbit | Sensor: %.1f deg Lat, %.1f deg Lon", ...
    orbitAltitude, ...
    rad2deg(sensorLatitude), ...
    rad2deg(sensorLongitude));

title(layout,figureTitle);

%% Plot measurement availability

figure( ...
    "Color","white", ...
    "Name","LRO Measurement Availability");

tiledlayout(2,1, ...
    "TileSpacing","compact", ...
    "Padding","compact");

nexttile;

plot( ...
    timeHours, ...
    rad2deg(topographicElevation), ...
    "LineWidth",1.3);

hold on;

yline( ...
    rad2deg(minimumSensorElevation), ...
    "k--", ...
    "Minimum elevation");

grid on;
xlabel("Time (hr)");
ylabel("Elevation (deg)");
title("Object Elevation from Surface Sensor");

nexttile;

stairs( ...
    timeHours, ...
    double(measurementAvailable), ...
    "LineWidth",1.3);

ylim([-0.1,1.1]);
yticks([0,1]);
yticklabels(["No LOS","LOS"]);
grid on;
xlabel("Time (hr)");
ylabel("Availability");
title("Measurement Availability Gate");

%% Local functions

function wrappedAngle = wrapAngle(angle)

wrappedAngle = atan2( ...
    sin(angle), ...
    cos(angle));

end

function finiteDifferenceJacobian = ...
    finiteDifferenceMeasurementJacobian( ...
        state,observerPositionMci)

numberOfStates = length(state);

finiteDifferenceJacobian = ...
    zeros(2,numberOfStates);

perturbationSizes = [ ...
    1e-3; ...
    1e-3; ...
    1e-3; ...
    1e-6; ...
    1e-6; ...
    1e-6];

for stateIndex = 1:numberOfStates

    statePerturbation = ...
        zeros(numberOfStates,1);

    statePerturbation(stateIndex) = ...
        perturbationSizes(stateIndex);

    measurementPlus = ...
        measurements.raDecMeasurement( ...
            state + statePerturbation, ...
            observerPositionMci);

    measurementMinus = ...
        measurements.raDecMeasurement( ...
            state - statePerturbation, ...
            observerPositionMci);

    measurementDifference = ...
        measurementPlus - measurementMinus;

    measurementDifference(1) = ...
        wrapAngle(measurementDifference(1));

    finiteDifferenceJacobian(:,stateIndex) = ...
        measurementDifference / ...
        (2*perturbationSizes(stateIndex));
end

