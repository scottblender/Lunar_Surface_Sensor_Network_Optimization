hold on;

plot( ...
    timeHours, ...
    velocityThreeSigmaNorm, ...
    "k--", ...
    "LineWidth",1.2);

grid on;
xlabel("Time (hr)");
ylabel("Velocity error (km/s)");
title("Velocity Estimation Error");
legend( ...
