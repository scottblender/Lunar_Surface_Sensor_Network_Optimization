%% Local functions

function [observerPositionsMci, ...
    measurementAvailable, ...
    topographicElevation, ...
    rightAscension, ...
    declination] = ...
    simulateSingleSurfaceSensor( ...
        times, ...
        truthStateHistory, ...
        sensorLatitude, ...
        sensorLongitude, ...
        dem, ...
        minimumElevation, ...
        measurementNoiseFactor, ...
        moonRadius, ...
        theta0, ...
        angularRate)

numberOfTimes = length(times);

sensorLongitude = ...
    mod(sensorLongitude,2*pi);

observerPositionsMci = ...
    zeros(numberOfTimes,3);

measurementAvailable = ...
    false(numberOfTimes,1);

topographicElevation = ...
    zeros(numberOfTimes,1);

rightAscension = ...
    NaN(numberOfTimes,1);

declination = ...
    NaN(numberOfTimes,1);

sensorMoonRotatingState = ...
    referenceFrames.topographic( ...
        zeros(6,1), ...
        sensorLatitude, ...
        sensorLongitude, ...
        dem, ...
        moonRadius, ...
        "toRotating");

for timeIndex = 1:numberOfTimes

    observationTime = ...
        times(timeIndex);

    truthState = ...
        truthStateHistory(:,timeIndex);

    sensorMciState = ...
        referenceFrames.moonRotating( ...
            sensorMoonRotatingState, ...
            observationTime, ...
            theta0, ...
            angularRate, ...
            "toInertial");

    observerPositionsMci(timeIndex,:) = ...
        sensorMciState(1:3).';

    truthMoonRotatingState = ...
        referenceFrames.moonRotating( ...
            truthState, ...
            observationTime, ...
            theta0, ...
            angularRate, ...
            "fromInertial");

    [~,topographicMeasurement] = ...
        referenceFrames.topographic( ...
            truthMoonRotatingState, ...
            sensorLatitude, ...
            sensorLongitude, ...
            dem, ...
            moonRadius, ...
            "fromRotating");

    elevation = ...
        topographicMeasurement(2);

    topographicElevation(timeIndex) = ...
        elevation;

    measurementAvailable(timeIndex) = ...
        elevation >= minimumElevation;

    if ~measurementAvailable(timeIndex)
        continue
    end

    idealMeasurement = ...
        measurements.surfaceRaDecMeasurement( ...
            truthState, ...
            observationTime, ...
            sensorLatitude, ...
            sensorLongitude, ...
            dem, ...
            moonRadius, ...
            theta0, ...
            angularRate);

    noisyMeasurement = ...
        idealMeasurement + ...
        measurementNoiseFactor*randn(2,1);

    noisyMeasurement(1) = ...
        wrapAngle(noisyMeasurement(1));

    rightAscension(timeIndex) = ...
        noisyMeasurement(1);

    declination(timeIndex) = ...
        noisyMeasurement(2);
end

end

function [observationTimes, ...
    rightAscension, ...
    declination, ...
    sensorLatitudes, ...
    sensorLongitudes, ...
    measurementAvailable] = ...
    simulateSelectedNetwork( ...
        times, ...
        truthStateHistory, ...
        selectedSensorIndices, ...
        candidateLatitudes, ...
        candidateLongitudes, ...
        dem, ...
        minimumElevation, ...
        measurementNoiseFactor, ...
        moonRadius, ...
        theta0, ...
        angularRate)

numberOfTimes = length(times);

numberOfSelectedSensors = ...
    length(selectedSensorIndices);

numberOfObservations = ...
    numberOfTimes*numberOfSelectedSensors;

observationTimes = ...
    zeros(numberOfObservations,1);

rightAscension = ...
    NaN(numberOfObservations,1);

declination = ...
    NaN(numberOfObservations,1);

sensorLatitudes = ...
    zeros(numberOfObservations,1);

sensorLongitudes = ...
    zeros(numberOfObservations,1);

measurementAvailable = ...
    false(numberOfObservations,1);

observationIndex = 0;

for timeIndex = 1:numberOfTimes

    observationTime = ...
        times(timeIndex);

    truthState = ...
        truthStateHistory(:,timeIndex);

    truthMoonRotatingState = ...
        referenceFrames.moonRotating( ...
            truthState, ...
            observationTime, ...
            theta0, ...
            angularRate, ...
            "fromInertial");

    for selectedIndex = 1:numberOfSelectedSensors

        observationIndex = ...
            observationIndex + 1;

        sensorIndex = ...
            selectedSensorIndices(selectedIndex);

        sensorLatitude = ...
            candidateLatitudes(sensorIndex);

        sensorLongitude = mod( ...
            candidateLongitudes(sensorIndex), ...
            2*pi);

        observationTimes(observationIndex) = ...
            observationTime;

        sensorLatitudes(observationIndex) = ...
            sensorLatitude;

        sensorLongitudes(observationIndex) = ...
            sensorLongitude;

        [~,topographicMeasurement] = ...
            referenceFrames.topographic( ...
                truthMoonRotatingState, ...
                sensorLatitude, ...
                sensorLongitude, ...
                dem, ...
                moonRadius, ...
                "fromRotating");

        elevation = ...
            topographicMeasurement(2);

        measurementAvailable(observationIndex) = ...
            elevation >= minimumElevation;

        if ~measurementAvailable(observationIndex)
            continue
        end

        idealMeasurement = ...
            measurements.surfaceRaDecMeasurement( ...
                truthState, ...
                observationTime, ...
                sensorLatitude, ...
                sensorLongitude, ...
                dem, ...
                moonRadius, ...
                theta0, ...
                angularRate);

        noisyMeasurement = ...
            idealMeasurement + ...
            measurementNoiseFactor*randn(2,1);

        noisyMeasurement(1) = ...
            wrapAngle(noisyMeasurement(1));

        rightAscension(observationIndex) = ...
