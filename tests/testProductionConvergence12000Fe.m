%% testProductionConvergence12000Fe
% Quick post-run convergence and sensor-placement diagnostic for the
% 12000-FE production campaign.
%
% This script does NOT rerun the optimizer and produces no figures. It finds
% the newest complete 12000-FE / 20-run production study for every objective
% and network size, verifies the saved histories, then reports:
%
%   1) convergence consistency and terminal slopes,
%   2) exact-network and exact-site diversity,
%   3) repeated/common sensor locations,
%   4) latitude-band preferences,
%   5) whether solutions accumulate at either latitude-domain boundary, and
%   6) longitude separation within the optimized networks.
%
% "Consistent plateau" is a practical diagnostic, not proof of the global
% optimum. Thresholds are explicit below.

clear;
clc;

%% ========================================================================
%  Project paths and production definition
%  ========================================================================

testDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(testDirectory);
runRoot = fullfile(projectRoot,"results","optimization_runs");
resultsDirectory = fullfile(projectRoot,"results");

assert(isfolder(runRoot), ...
    "Optimization result directory was not found: %s",runRoot);

networkSizes = [3 5 7 10];
objectiveModes = ["information","coverage"];

numberOfRuns = 20;
functionEvaluationBudget = 12000;
populationSize = 60;
baseSeed = 1000;
studyName = "lunar_surface_production_optimization";

latitudeDomainDeg = [-90,0];

%% ========================================================================
%  Diagnostic settings
%  ========================================================================

% Linear terminal slope is fitted over the final quarter of each history.
terminalWindowFraction = 0.25;

% Convergence consistency heuristic:
%   - 90% of runs must have a terminal slope magnitude below this fraction
%     of their total optimization gain per 1000 FE,
%   - 90% of runs must obtain no more than this fraction of their total gain
%     during the final quarter of the FE budget,
%   - final run-to-run standard deviation must be small relative to the mean
%     optimization gain.
maximumP90AbsNormalizedSlopePctPer1000Fe = 0.50;
maximumP90LateImprovementPct = 5.0;
maximumFinalStdToMeanGainPct = 5.0;

% Placement diagnostics.
boundaryBandDeg = 5;
latitudeBinWidthDeg = 5;
numberOfCommonSitesToPrint = 5;
numberOfLatitudeBandsToPrint = 3;

writeCsv = true;

%% ========================================================================
%  Discover completed studies
%  ========================================================================

summaryFiles = dir(fullfile(runRoot,"*","study_summary.mat"));

assert(~isempty(summaryFiles), ...
    "No production study summaries were found.");

[~,order] = sort([summaryFiles.datenum],"descend");
summaryFiles = summaryFiles(order);

numberOfCases = numel(networkSizes)*numel(objectiveModes);

%% ========================================================================
%  Allocate convergence summary
%  ========================================================================

objectiveColumn = strings(numberOfCases,1);
networkSizeColumn = zeros(numberOfCases,1);

finalMeanObjective = zeros(numberOfCases,1);
finalStdObjective = zeros(numberOfCases,1);
bestWorstGap = zeros(numberOfCases,1);
meanTotalGain = zeros(numberOfCases,1);

meanTerminalSlopePer1000Fe = zeros(numberOfCases,1);
p90AbsNormalizedSlopePctPer1000Fe = zeros(numberOfCases,1);
p90LateImprovementPct = zeros(numberOfCases,1);
finalStdToMeanGainPct = zeros(numberOfCases,1);

consistentPlateau = false(numberOfCases,1);
convergenceDiagnostic = strings(numberOfCases,1);

%% ========================================================================
%  Allocate placement summary
%  ========================================================================

uniqueNetworkCount = zeros(numberOfCases,1);
mostRepeatedNetworkRuns = zeros(numberOfCases,1);

totalPlacements = zeros(numberOfCases,1);
uniqueSiteCount = zeros(numberOfCases,1);
mostCommonSiteRuns = zeros(numberOfCases,1);
mostCommonSiteLatitudeDeg = zeros(numberOfCases,1);
mostCommonSiteLongitudeDeg = zeros(numberOfCases,1);

exactBoundaryPlacementPct = zeros(numberOfCases,1);
withinBoundaryBandPlacementPct = zeros(numberOfCases,1);
nearEquatorPlacementPct = zeros(numberOfCases,1);
nearSouthPolePlacementPct = zeros(numberOfCases,1);

latitudeP10Deg = zeros(numberOfCases,1);
latitudeMedianDeg = zeros(numberOfCases,1);
latitudeP90Deg = zeros(numberOfCases,1);

meanPairwiseLongitudeSeparationDeg = zeros(numberOfCases,1);

topLatitudeBand = strings(numberOfCases,1);
topLatitudeBandPlacementPct = zeros(numberOfCases,1);

studyFileColumn = strings(numberOfCases,1);

commonSiteTables = cell(numberOfCases,1);
latitudeBandTables = cell(numberOfCases,1);

%% ========================================================================
%  Process all eight production cases
%  ========================================================================

row = 0;

for objectiveIndex = 1:numel(objectiveModes)

    objectiveMode = objectiveModes(objectiveIndex);

    for networkIndex = 1:numel(networkSizes)

        networkSize = networkSizes(networkIndex);
        row = row + 1;

        [studyState,summaryFile] = findStudy( ...
            summaryFiles, ...
            networkSize, ...
            objectiveMode, ...
            numberOfRuns, ...
            functionEvaluationBudget, ...
            populationSize, ...
            baseSeed, ...
            studyName);

        assert(numel(studyState.runStates) == numberOfRuns, ...
            "Study contains the wrong number of runs.");

        referenceFe = ...
            double(studyState.runStates{1}.history.fe(:));

        assert(referenceFe(end) == functionEvaluationBudget, ...
            "Convergence history does not reach 12000 FE.");

        assert(all(diff(referenceFe) > 0), ...
            "FE history is not strictly increasing.");

        terminalStartFe = ...
            functionEvaluationBudget*(1-terminalWindowFraction);

        terminalMask = ...
            referenceFe >= terminalStartFe;

        assert(nnz(terminalMask) >= 3, ...
            "Too few terminal convergence points.");

        terminalFe = referenceFe(terminalMask);

        historyMatrix = zeros(numel(referenceFe),numberOfRuns);
        runFinalObjectives = zeros(numberOfRuns,1);
        runTotalGain = zeros(numberOfRuns,1);
        runLateImprovementPct = zeros(numberOfRuns,1);
        runAbsNormalizedSlopePctPer1000Fe = zeros(numberOfRuns,1);

        sensorIndexMatrix = zeros(numberOfRuns,networkSize);
        sensorLatitudeMatrix = zeros(numberOfRuns,networkSize);
        sensorLongitudeMatrix = zeros(numberOfRuns,networkSize);
        runMeanPairwiseLongitudeSeparation = zeros(numberOfRuns,1);

        terminalStartIndex = find(terminalMask,1,"first");

        for runIndex = 1:numberOfRuns

            runState = studyState.runStates{runIndex};

            runFe = double(runState.history.fe(:));
            runBest = double(runState.history.bestJ(:));

            assert(isequal(runFe,referenceFe), ...
                "Run FE histories are not aligned.");

            assert(numel(runBest) == numel(referenceFe), ...
                "Run best-objective history has the wrong length.");

            assert(all(isfinite(runBest)), ...
                "Run convergence history contains nonfinite values.");

            assert(all(diff(runBest) <= 1e-12), ...
                "Saved best-so-far history increased within a run.");

            assert(runState.searchFunctionEvaluations == ...
                functionEvaluationBudget, ...
                "Saved run did not use the full 12000-FE budget.");

            objectiveTolerance = ...
                1e-10*max(1,abs(runState.bestObjective));

            assert(abs(runBest(end)-runState.bestObjective) <= ...
                objectiveTolerance, ...
                "Run history does not terminate at the stored incumbent.");

            historyMatrix(:,runIndex) = runBest;
            runFinalObjectives(runIndex) = runBest(end);

            totalGain = runBest(1)-runBest(end);
            lateGain = runBest(terminalStartIndex)-runBest(end);

            gainTolerance = ...
                1e-12*max(1,abs(runBest(1)));

            if totalGain > gainTolerance
                runLateImprovementPct(runIndex) = ...
                    100*lateGain/totalGain;
                gainScale = totalGain;
            else
                runLateImprovementPct(runIndex) = 0;
                gainScale = max(gainTolerance,eps);
            end

            terminalCoefficients = ...
                polyfit(terminalFe,runBest(terminalMask),1);

            runAbsNormalizedSlopePctPer1000Fe(runIndex) = ...
                100*abs(terminalCoefficients(1)*1000)/gainScale;

            runTotalGain(runIndex) = totalGain;

            %% Sensor placement for this run

            sensorIndices = ...
                double(runState.bestSensorIndices(:).');

            sensorLatitudesDeg = ...
                rad2deg(double(runState.bestSensorLatitudesRad(:).'));

            sensorLongitudesDeg = ...
                mod( ...
                    rad2deg(double(runState.bestSensorLongitudesRad(:).')), ...
                    360);

            assert(numel(sensorIndices) == networkSize, ...
                "Stored best network has the wrong sensor count.");

            assert(numel(unique(sensorIndices)) == networkSize, ...
                "Stored best network contains duplicate sensors.");

            sensorIndexMatrix(runIndex,:) = sensorIndices;
            sensorLatitudeMatrix(runIndex,:) = sensorLatitudesDeg;
            sensorLongitudeMatrix(runIndex,:) = sensorLongitudesDeg;

            runMeanPairwiseLongitudeSeparation(runIndex) = ...
                meanPairwiseCircularSeparationDeg(sensorLongitudesDeg);
        end

        %% ----------------------------------------------------------------
        %  Convergence metrics
        %  ----------------------------------------------------------------

        meanHistory = mean(historyMatrix,2);
        meanTerminalCoefficients = ...
            polyfit(terminalFe,meanHistory(terminalMask),1);

        finalMean = mean(runFinalObjectives);
        finalStd = std(runFinalObjectives);
        caseMeanGain = mean(runTotalGain);

        meanGainScale = max( ...
            caseMeanGain, ...
            1e-12*max(1,abs(finalMean)));

        caseP90SlopePct = ...
            localPercentile( ...
                runAbsNormalizedSlopePctPer1000Fe,90);

        caseP90LatePct = ...
            localPercentile(runLateImprovementPct,90);

        caseStdToGainPct = ...
            100*finalStd/meanGainScale;

        caseConsistentPlateau = ...
            caseP90SlopePct <= ...
                maximumP90AbsNormalizedSlopePctPer1000Fe && ...
            caseP90LatePct <= ...
                maximumP90LateImprovementPct && ...
            caseStdToGainPct <= ...
                maximumFinalStdToMeanGainPct;

        caseDiagnostic = classifyConvergence( ...
            caseP90SlopePct, ...
            caseP90LatePct, ...
            caseStdToGainPct, ...
            maximumP90AbsNormalizedSlopePctPer1000Fe, ...
            maximumP90LateImprovementPct, ...
            maximumFinalStdToMeanGainPct);

        %% ----------------------------------------------------------------
        %  Exact network/site diversity
        %  ----------------------------------------------------------------

        [~,~,networkGroup] = ...
            unique(sensorIndexMatrix,"rows");

        networkCounts = ...
            accumarray(networkGroup,1);

        caseUniqueNetworkCount = ...
            numel(networkCounts);

        caseMostRepeatedNetworkRuns = ...
            max(networkCounts);

        allSensorIndices = sensorIndexMatrix(:);
        allLatitudesDeg = sensorLatitudeMatrix(:);
        allLongitudesDeg = sensorLongitudeMatrix(:);

        [uniqueSites,~,siteGroup] = ...
            unique(allSensorIndices);

        siteCounts = ...
            accumarray(siteGroup,1);

        [sortedSiteCounts,siteOrder] = ...
            sort(siteCounts,"descend");

        sortedUniqueSites = ...
            uniqueSites(siteOrder);

        numberOfCommonSites = min( ...
            numberOfCommonSitesToPrint, ...
            numel(sortedUniqueSites));

        commonSiteRank = (1:numberOfCommonSites).';
        commonSiteIndex = ...
            sortedUniqueSites(1:numberOfCommonSites);

        commonSiteCount = ...
            sortedSiteCounts(1:numberOfCommonSites);

        commonSiteRunPct = ...
            100*commonSiteCount/numberOfRuns;

        commonSiteLatitude = ...
            zeros(numberOfCommonSites,1);

        commonSiteLongitude = ...
            zeros(numberOfCommonSites,1);

        for siteRank = 1:numberOfCommonSites

            occurrenceIndex = find( ...
                allSensorIndices == commonSiteIndex(siteRank), ...
                1, ...
                "first");

            commonSiteLatitude(siteRank) = ...
                allLatitudesDeg(occurrenceIndex);

            commonSiteLongitude(siteRank) = ...
                allLongitudesDeg(occurrenceIndex);
        end

        commonSiteTable = table( ...
            repmat(objectiveMode,numberOfCommonSites,1), ...
            repmat(networkSize,numberOfCommonSites,1), ...
            commonSiteRank, ...
            commonSiteIndex, ...
            commonSiteLatitude, ...
            commonSiteLongitude, ...
            commonSiteCount, ...
            commonSiteRunPct, ...
            'VariableNames',{ ...
                'Objective', ...
                'NetworkSize', ...
                'Rank', ...
                'CandidateIndex', ...
                'LatitudeDeg', ...
                'LongitudeDeg', ...
                'Occurrences', ...
                'RunsPct'});

        commonSiteTables{row} = commonSiteTable;

        %% ----------------------------------------------------------------
        %  Boundary and geographic-distribution diagnostics
        %  ----------------------------------------------------------------

        latitudeDistanceToBoundary = min( ...
            abs(allLatitudesDeg-latitudeDomainDeg(1)), ...
            abs(allLatitudesDeg-latitudeDomainDeg(2)));

        exactBoundaryToleranceDeg = 1e-10;

        caseExactBoundaryPct = ...
            100*mean( ...
                latitudeDistanceToBoundary <= ...
                exactBoundaryToleranceDeg);

        caseWithinBoundaryBandPct = ...
            100*mean( ...
                latitudeDistanceToBoundary <= ...
                boundaryBandDeg);

        caseNearEquatorPct = ...
            100*mean( ...
                allLatitudesDeg >= ...
                latitudeDomainDeg(2)-boundaryBandDeg);

        caseNearSouthPolePct = ...
            100*mean( ...
                allLatitudesDeg <= ...
                latitudeDomainDeg(1)+boundaryBandDeg);

        caseLatitudeP10 = ...
            localPercentile(allLatitudesDeg,10);

        caseLatitudeMedian = ...
            median(allLatitudesDeg);

        caseLatitudeP90 = ...
            localPercentile(allLatitudesDeg,90);

        caseMeanLongitudeSeparation = ...
            mean(runMeanPairwiseLongitudeSeparation);

        %% ----------------------------------------------------------------
        %  Latitude-band frequency
        %  ----------------------------------------------------------------

        [latitudeBandTable,caseTopBand,caseTopBandPct] = ...
            buildLatitudeBandTable( ...
                allLatitudesDeg, ...
                objectiveMode, ...
                networkSize, ...
                latitudeDomainDeg, ...
                latitudeBinWidthDeg, ...
                numberOfLatitudeBandsToPrint);

        latitudeBandTables{row} = latitudeBandTable;

        %% ----------------------------------------------------------------
        %  Store summaries
        %  ----------------------------------------------------------------

        objectiveColumn(row) = objectiveMode;
        networkSizeColumn(row) = networkSize;

        finalMeanObjective(row) = finalMean;
        finalStdObjective(row) = finalStd;
        bestWorstGap(row) = ...
            max(runFinalObjectives)-min(runFinalObjectives);
        meanTotalGain(row) = caseMeanGain;

        meanTerminalSlopePer1000Fe(row) = ...
            meanTerminalCoefficients(1)*1000;

        p90AbsNormalizedSlopePctPer1000Fe(row) = ...
            caseP90SlopePct;

        p90LateImprovementPct(row) = ...
            caseP90LatePct;

        finalStdToMeanGainPct(row) = ...
            caseStdToGainPct;

        consistentPlateau(row) = ...
            caseConsistentPlateau;

        convergenceDiagnostic(row) = ...
            caseDiagnostic;

        uniqueNetworkCount(row) = ...
            caseUniqueNetworkCount;

        mostRepeatedNetworkRuns(row) = ...
            caseMostRepeatedNetworkRuns;

        totalPlacements(row) = ...
            numel(allSensorIndices);

        uniqueSiteCount(row) = ...
            numel(uniqueSites);

        mostCommonSiteRuns(row) = ...
            sortedSiteCounts(1);

        mostCommonSiteLatitudeDeg(row) = ...
            commonSiteLatitude(1);

        mostCommonSiteLongitudeDeg(row) = ...
            commonSiteLongitude(1);

        exactBoundaryPlacementPct(row) = ...
            caseExactBoundaryPct;

        withinBoundaryBandPlacementPct(row) = ...
            caseWithinBoundaryBandPct;

        nearEquatorPlacementPct(row) = ...
            caseNearEquatorPct;

        nearSouthPolePlacementPct(row) = ...
            caseNearSouthPolePct;

        latitudeP10Deg(row) = ...
            caseLatitudeP10;

        latitudeMedianDeg(row) = ...
            caseLatitudeMedian;

        latitudeP90Deg(row) = ...
            caseLatitudeP90;

        meanPairwiseLongitudeSeparationDeg(row) = ...
            caseMeanLongitudeSeparation;

        topLatitudeBand(row) = ...
            caseTopBand;

        topLatitudeBandPlacementPct(row) = ...
            caseTopBandPct;

        studyFileColumn(row) = ...
            string(summaryFile);
    end
end

