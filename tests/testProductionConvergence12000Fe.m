function [studyState,summaryFile] = findStudy( ...
    summaryFiles, ...
    networkSize, ...
    objectiveMode, ...
    numberOfRuns, ...
    functionEvaluationBudget, ...
    populationSize, ...
    baseSeed, ...
    studyName)

for fileIndex = 1:numel(summaryFiles)

    candidateFile = fullfile( ...
        summaryFiles(fileIndex).folder, ...
        summaryFiles(fileIndex).name);

    data = load(candidateFile,"studyState");

    if ~isfield(data,"studyState")
        continue
    end

    candidate = data.studyState;

    if ~isfield(candidate,"config") || ...
            ~isfield(candidate,"numberOfRuns") || ...
            candidate.numberOfRuns ~= numberOfRuns
        continue
    end

    cfg = candidate.config;

    requiredFields = [ ...
        "networkSize", ...
        "objectiveMode", ...
        "functionEvaluationBudget", ...
        "populationSize", ...
        "baseSeed", ...
        "studyName"];

    if ~all(isfield(cfg,cellstr(requiredFields)))
        continue
    end

    if cfg.networkSize ~= networkSize || ...
            lower(string(cfg.objectiveMode)) ~= objectiveMode || ...
            cfg.functionEvaluationBudget ~= functionEvaluationBudget || ...
            cfg.populationSize ~= populationSize || ...
            cfg.baseSeed ~= baseSeed || ...
            string(cfg.studyName) ~= studyName
        continue
    end

    studyState = candidate;
    summaryFile = candidateFile;
    return
end

error( ...
    "testProductionConvergence12000Fe:StudyNotFound", ...
    "No complete 12000-FE production study found for N=%d, %s.", ...
    networkSize,objectiveMode);

end

function value = localPercentile(values,percent)

values = sort(values(:));
numberOfValues = numel(values);

assert(numberOfValues >= 1, ...
    "Cannot evaluate a percentile of an empty array.");

if numberOfValues == 1
    value = values(1);
    return
end

position = 1 + (numberOfValues-1)*(percent/100);
lowerIndex = floor(position);
upperIndex = ceil(position);

if lowerIndex == upperIndex
    value = values(lowerIndex);
else
    interpolationFraction = position-lowerIndex;
    value = ...
        values(lowerIndex) + ...
        interpolationFraction*( ...
            values(upperIndex)-values(lowerIndex));
end

end

function label = classifyConvergence( ...
    p90SlopePct, ...
    p90LatePct, ...
    stdToGainPct, ...
    slopeThresholdPct, ...
    lateThresholdPct, ...
    spreadThresholdPct)

slopeOkay = ...
    p90SlopePct <= slopeThresholdPct;

lateOkay = ...
    p90LatePct <= lateThresholdPct;

spreadOkay = ...
    stdToGainPct <= spreadThresholdPct;

if slopeOkay && lateOkay && spreadOkay
    label = "consistent plateau";
elseif ~slopeOkay && ~lateOkay
    label = "still improving";
elseif slopeOkay && lateOkay && ~spreadOkay
    label = "plateau, run spread remains";
elseif ~slopeOkay
    label = "terminal slope remains";
elseif ~lateOkay
    label = "late improvements remain";
else
    label = "mixed";
end

end

function meanSeparationDeg = ...
    meanPairwiseCircularSeparationDeg(longitudesDeg)

longitudesDeg = mod(longitudesDeg(:),360);
numberOfLongitudes = numel(longitudesDeg);

if numberOfLongitudes < 2
    meanSeparationDeg = 0;
    return
end

separations = zeros( ...
    numberOfLongitudes*(numberOfLongitudes-1)/2, ...
    1);

pairIndex = 0;

for firstIndex = 1:numberOfLongitudes-1
    for secondIndex = firstIndex+1:numberOfLongitudes

        pairIndex = pairIndex + 1;

        delta = ...
            longitudesDeg(secondIndex)- ...
            longitudesDeg(firstIndex);

        separations(pairIndex) = ...
            abs(mod(delta+180,360)-180);
    end
end

meanSeparationDeg = mean(separations);

end

function [topTable,topBandLabel,topBandPct] = ...
    buildLatitudeBandTable( ...
        latitudesDeg, ...
        objectiveMode, ...
        networkSize, ...
        latitudeDomainDeg, ...
        binWidthDeg, ...
        numberToReturn)

minimumLatitude = latitudeDomainDeg(1);
maximumLatitude = latitudeDomainDeg(2);

numberOfBins = round( ...
    (maximumLatitude-minimumLatitude)/binWidthDeg);

assert(abs( ...
    minimumLatitude + ...
    numberOfBins*binWidthDeg - ...
    maximumLatitude) < 1e-12, ...
    "Latitude bin width must exactly divide the latitude domain.");

binCounts = zeros(numberOfBins,1);
binLabels = strings(numberOfBins,1);

for binIndex = 1:numberOfBins

    lowerEdge = ...
        minimumLatitude + ...
        (binIndex-1)*binWidthDeg;

    upperEdge = ...
        lowerEdge + binWidthDeg;

    if binIndex < numberOfBins
        inBin = ...
            latitudesDeg >= lowerEdge & ...
            latitudesDeg < upperEdge;

        binLabels(binIndex) = sprintf( ...
            "[%.0f, %.0f)", ...
            lowerEdge, ...
            upperEdge);
    else
        inBin = ...
            latitudesDeg >= lowerEdge & ...
            latitudesDeg <= upperEdge;

        binLabels(binIndex) = sprintf( ...
            "[%.0f, %.0f]", ...
            lowerEdge, ...
            upperEdge);
    end

    binCounts(binIndex) = nnz(inBin);
end

[sortedCounts,order] = ...
    sort(binCounts,"descend");

numberToReturn = min(numberToReturn,numberOfBins);

selectedOrder = ...
    order(1:numberToReturn);

rank = (1:numberToReturn).';
band = binLabels(selectedOrder);
count = sortedCounts(1:numberToReturn);
placementPct = 100*count/numel(latitudesDeg);

topTable = table( ...
    repmat(objectiveMode,numberToReturn,1), ...
    repmat(networkSize,numberToReturn,1), ...
    rank, ...
    band, ...
    count, ...
    placementPct, ...
    'VariableNames',{ ...
        'Objective', ...
        'NetworkSize', ...
        'Rank', ...
        'LatitudeBandDeg', ...
        'Placements', ...
        'PlacementPct'});

topBandLabel = band(1);
topBandPct = placementPct(1);

end

function output = upperFirst(input)

input = string(input);

if strlength(input) == 0
    output = input;
    return
end

characters = char(input);
characters(1) = upper(characters(1));
output = string(characters);

end
