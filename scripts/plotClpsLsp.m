%% ========================================================================
%  Local functions
%  ========================================================================

function [xKm,yKm] = polarCoordinates( ...
    latitudeDeg, ...
    longitudeDeg, ...
    moonRadiusKm)

radialDistanceKm = ...
    moonRadiusKm .* ...
    deg2rad(90 + latitudeDeg);

xKm = ...
    radialDistanceKm .* ...
    sind(longitudeDeg);

yKm = ...
    radialDistanceKm .* ...
    cosd(longitudeDeg);

end

function [regionXKm,regionYKm] = ...
    rectangularPolarRegion( ...
        latitudeSouthDeg, ...
        latitudeNorthDeg, ...
        longitudeWestDeg, ...
        longitudeEastDeg, ...
        moonRadiusKm)

numberOfArcPoints = 160;
numberOfEdgePoints = 80;

%% Northern boundary

northLongitudeDeg = linspace( ...
    longitudeWestDeg, ...
    longitudeEastDeg, ...
    numberOfArcPoints);

northLatitudeDeg = ...
    latitudeNorthDeg .* ...
    ones(size(northLongitudeDeg));

%% Eastern boundary

eastLatitudeDeg = linspace( ...
    latitudeNorthDeg, ...
    latitudeSouthDeg, ...
    numberOfEdgePoints);

eastLongitudeDeg = ...
    longitudeEastDeg .* ...
    ones(size(eastLatitudeDeg));

%% Southern boundary

southLongitudeDeg = linspace( ...
    longitudeEastDeg, ...
    longitudeWestDeg, ...
    numberOfArcPoints);

southLatitudeDeg = ...
    latitudeSouthDeg .* ...
    ones(size(southLongitudeDeg));

%% Western boundary

westLatitudeDeg = linspace( ...
    latitudeSouthDeg, ...
    latitudeNorthDeg, ...
    numberOfEdgePoints);

westLongitudeDeg = ...
    longitudeWestDeg .* ...
    ones(size(westLatitudeDeg));

%% Assemble polygon

regionLatitudeDeg = [ ...
    northLatitudeDeg, ...
    eastLatitudeDeg, ...
    southLatitudeDeg, ...
    westLatitudeDeg ...
];

regionLongitudeDeg = [ ...
    northLongitudeDeg, ...
    eastLongitudeDeg, ...
    southLongitudeDeg, ...
    westLongitudeDeg ...
];

[regionXKm,regionYKm] = ...
    polarCoordinates( ...
        regionLatitudeDeg, ...
        regionLongitudeDeg, ...
        moonRadiusKm);

end