    outerRadiusKm + 38;

longitudeLabelText = [
    "0^{\circ}E"
    "90^{\circ}E"
    "180^{\circ}E"
    "270^{\circ}E"
];

for longitudeIndex = 1:numel(longitudeGridDeg)

    currentLongitudeDeg = ...
        longitudeGridDeg(longitudeIndex);

    labelXKm = ...
        longitudeLabelRadiusKm .* ...
        sind(currentLongitudeDeg);

    labelYKm = ...
        longitudeLabelRadiusKm .* ...
        cosd(currentLongitudeDeg);

    text(detailAxes, ...
        labelXKm, ...
        labelYKm, ...
        longitudeLabelText(longitudeIndex), ...
        "Interpreter","tex", ...
        "Color","white", ...
        "FontName",fontName, ...
        "FontSize",gridFontSize, ...
        "FontWeight","bold", ...
        "BackgroundColor",boxColor, ...
        "EdgeColor","none", ...
        "Margin",1.5, ...
        "HorizontalAlignment","center", ...
        "VerticalAlignment","middle");

end

%% ========================================================================
%  Latitude labels
%
%  Dark backing is used because these labels lie directly on the DEM.
%  ========================================================================

latitudeLabelLongitudeDeg = 225;

latitudeLabelOffsetXKm = -8;
latitudeLabelOffsetYKm = 7;

for latitudeIndex = 1:2

    currentLatitudeDeg = ...
        latitudeGridDeg(latitudeIndex);

    currentRadiusKm = ...
        moonRadiusKm * ...
        deg2rad(90 + currentLatitudeDeg);

    labelXKm = ...
        currentRadiusKm .* ...
        sind(latitudeLabelLongitudeDeg);

    labelYKm = ...
        currentRadiusKm .* ...
        cosd(latitudeLabelLongitudeDeg);

    text(detailAxes, ...
        labelXKm + latitudeLabelOffsetXKm, ...
        labelYKm + latitudeLabelOffsetYKm, ...
        sprintf("%d^{\\circ}S", ...
        abs(currentLatitudeDeg)), ...
        "Interpreter","tex", ...
        "Color","white", ...
        "FontName",fontName, ...
        "FontSize",gridFontSize, ...
        "FontWeight","bold", ...
        "BackgroundColor",boxColor, ...
        "EdgeColor","none", ...
        "Margin",1.5, ...
        "HorizontalAlignment","right", ...
        "VerticalAlignment","middle");

end

%% ========================================================================
%  South Pole
%  ========================================================================

plot(detailAxes, ...
    0, ...
    0, ...
    ".", ...
    "Color","white", ...
    "MarkerSize",14);

text(detailAxes, ...
    -18, ...
    -18, ...
    "South Pole", ...
    "Color","white", ...
    "FontName",fontName, ...
    "FontSize",gridFontSize, ...
    "FontWeight","bold", ...
    "BackgroundColor",boxColor, ...
    "EdgeColor","none", ...
    "Margin",1.5, ...
