%% plotClpsLsp
% Generate the detailed CLPS lunar south-polar figure.
%
% Output:
%   CLPS_LSP_Detail.eps
%
% The figure shows:
%   - DEM elevation over the lunar south-polar optimization domain
%   - Completed CLPS landing sites
%   - Planned Mons Mouton deployment region
%   - Optional Schrodinger Basin overlap
%   - LSP-wide planned deployment anchors
%
% Optimization domain:
%   -90 deg <= latitude <= -75 deg
%      0 deg <= longitude < 360 deg

clear;
close all;
clc;

%% ========================================================================
%  Figure typography and styling
%  ========================================================================

fontName = "Arial";

% Minimum font size: 12 pt
siteFontSize = 12;
calloutFontSize = 12;
gridFontSize = 12;
boundaryFontSize = 12;
legendFontSize = 12;
colorbarFontSize = 12;

% Colors
boxColor = [0.045 0.045 0.055];
boxEdgeColor = [0.55 0.55 0.55];

completedColor = [1.00 0.08 0.08];
plannedColor = [1.00 0.00 0.85];
optionalColor = [1.00 0.55 0.05];
boundaryColor = [0.10 0.85 1.00];

% Grid styling
gridColor = [0.15 0.15 0.15];

% Callout arrows
arrowLineWidth = 2.2;
arrowHeadSize = 1.0;

%% ========================================================================
%  Load DEM
%  ========================================================================

scriptDirectory = fileparts(mfilename("fullpath"));
repositoryRoot = fileparts(scriptDirectory);

demFile = fullfile( ...
    repositoryRoot, ...
    "data", ...
    "new_lunar_interpolant_model.mat");

assert(isfile(demFile), ...
    "DEM file was not found: %s",demFile);

loadedData = load(demFile);
variableNames = fieldnames(loadedData);

demInterpolant = [];

for variableIndex = 1:numel(variableNames)

    currentVariable = ...
        loadedData.(variableNames{variableIndex});

    if isa(currentVariable,"griddedInterpolant")
        demInterpolant = currentVariable;
        break;
    end

end

assert(~isempty(demInterpolant), ...
    "No griddedInterpolant was found in %s.",demFile);

%% ========================================================================
%  Constants
%  ========================================================================

moonRadiusKm = 1737.4;

domainSouthDeg = -90.0;
domainNorthDeg = -75.0;

%% ========================================================================
%  Evaluate south-polar DEM
%  ========================================================================

longitudeDeg = linspace(0.0,360.0,721);

latitudeDeg = linspace( ...
    domainSouthDeg, ...
    domainNorthDeg, ...
    301);

[longitudeMeshDeg,latitudeMeshDeg] = meshgrid( ...
    longitudeDeg, ...
    latitudeDeg);

% Repository convention:
%
%   elevation = F(latitude,longitude)

elevationKm = double(demInterpolant( ...
    latitudeMeshDeg, ...
    longitudeMeshDeg));

finiteElevationKm = elevationKm(isfinite(elevationKm));

elevationLimitsKm = [ ...
    min(finiteElevationKm), ...
    max(finiteElevationKm)];

%% ========================================================================
%  Completed CLPS landing sites
%  ========================================================================

% IM-1 / TO2-IM
% Near Malapert A
%
% IM-2 / PRIME-1
% Mons Mouton

completedLatitudeDeg = [
    -80.1277
    -84.7754
];

completedLongitudeDeg = [
      1.4357
     29.1264
];

%% ========================================================================
%  Mons Mouton planned region
%  ========================================================================

% Griffin / TO20A
% IM-4 / CP-22

monsLatitudeSouthDeg = -86.22;
monsLatitudeNorthDeg = -83.30;

monsLongitudeWestDeg = 11.67;
monsLongitudeEastDeg = 53.03;

%% ========================================================================
%  Schrodinger Basin overlap
%  ========================================================================

% Published regional extent:
%
%   latitude  = [-79.95,-69.52] deg
%   longitude = [112.33,153.44] deg E
%
% Only the portion overlapping the optimization domain is displayed.

schrodingerLatitudeSouthDeg = -79.95;
schrodingerLatitudeNorthDeg = domainNorthDeg;

schrodingerLongitudeWestDeg = 112.33;
schrodingerLongitudeEastDeg = 153.44;

%% ========================================================================
%  Create figure
%  ========================================================================

detailFigure = figure( ...
    "Color","black", ...
    "Units","inches", ...
    "Position",[1 1 10.5 6.8]);

detailFigure.InvertHardcopy = "off";

detailAxes = axes( ...
    detailFigure, ...
    "Position",[0.055 0.115 0.80 0.83]);

hold(detailAxes,"on");

detailAxes.Color = "black";
detailAxes.FontName = fontName;
detailAxes.SortMethod = "childorder";

%% ========================================================================
%  Convert DEM to south-polar coordinates
%
%  Orientation:
%
%       0 E   = top
%       90 E  = right
%       180 E = bottom
%       270 E = left
%  ========================================================================

polarDistanceKm = ...
    moonRadiusKm .* ...
    deg2rad(90.0 + latitudeMeshDeg);

detailXKm = ...
    polarDistanceKm .* ...
    sind(longitudeMeshDeg);

detailYKm = ...
    polarDistanceKm .* ...
    cosd(longitudeMeshDeg);

outerRadiusKm = ...
    moonRadiusKm * ...
    deg2rad(15.0);

%% ========================================================================
%  Plot DEM
%  ========================================================================

surf(detailAxes, ...
    detailXKm, ...
    detailYKm, ...
    zeros(size(detailXKm)), ...
    elevationKm, ...
    "EdgeColor","none", ...
    "FaceColor","interp");

view(detailAxes,2);

colormap(detailAxes,turbo(256));
clim(detailAxes,elevationLimitsKm);

%% ========================================================================
%  Latitude circles
%  ========================================================================

circleAngleDeg = linspace(0,360,721);

latitudeGridDeg = [
    -85
    -80
    -75
];

for latitudeIndex = 1:numel(latitudeGridDeg)

    currentLatitudeDeg = ...
        latitudeGridDeg(latitudeIndex);

    currentRadiusKm = ...
        moonRadiusKm * ...
        deg2rad(90 + currentLatitudeDeg);

    circleXKm = ...
        currentRadiusKm .* ...
        sind(circleAngleDeg);

    circleYKm = ...
        currentRadiusKm .* ...
        cosd(circleAngleDeg);

    if currentLatitudeDeg == domainNorthDeg

        % Optimization boundary
        plot(detailAxes, ...
            circleXKm, ...
            circleYKm, ...
            "Color",boundaryColor, ...
            "LineWidth",2.4);

    else

        % Internal latitude grid
        plot(detailAxes, ...
            circleXKm, ...
            circleYKm, ...
            "--", ...
            "Color",gridColor, ...
            "LineWidth",1.0);

    end

end

%% ========================================================================
%  Longitude spokes
%  ========================================================================

longitudeGridDeg = [
      0
     90
    180
    270
];

for longitudeIndex = 1:numel(longitudeGridDeg)

    currentLongitudeDeg = ...
        longitudeGridDeg(longitudeIndex);

    radialDistanceKm = [
        0
        outerRadiusKm
    ];

    spokeXKm = ...
        radialDistanceKm .* ...
        sind(currentLongitudeDeg);

    spokeYKm = ...
        radialDistanceKm .* ...
        cosd(currentLongitudeDeg);

    plot(detailAxes, ...
        spokeXKm, ...
        spokeYKm, ...
        "--", ...
        "Color",gridColor, ...
        "LineWidth",1.0);

end

%% ========================================================================
%  Longitude labels
%
%  Place these slightly farther outside the cyan optimization boundary and
%  add a dark backing so white text remains readable regardless of the DEM.
%  ========================================================================

