function plotInfo = plotClpsDesignDomain(userConfig)
% PLOTCLPSDESIGNDOMAIN Generate the detailed CLPS south-polar context figure.
%
% This restores the mission callouts, regional overlays, coordinate labels,
% and deployment context from the original manuscript CLPS_LSP_Detail figure,
% while updating the 75-deg boundary language for the present matched
% restricted-domain comparison. The legend is intentionally centered beneath
% the map because this figure is a geographic composition rather than a
% conventional Cartesian results plot.
%
% Output:
%   CLPS_Southern_Hemisphere_Design_Domain.eps

arguments
    userConfig (1,1) struct = struct()
end

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
dataDirectory = fullfile(projectRoot,"data");
sourceDirectory = fullfile(projectRoot,"src");
addpath(scriptDirectory);
addpath(sourceDirectory);
rehash path;

defaults = struct();
defaults.outputDirectory = fullfile(projectRoot,"results","manuscript_artifacts");
defaults.demFile = fullfile(dataDirectory,"Full_Resolution_DEM.mat");
defaults.moonRadiusKm = 1737.4;
config = mergeStruct(defaults,userConfig);
style = publicationPlotStyle();

assert(isfile(config.demFile),"Full DEM was not found: %s",config.demFile);
[demInterpolant,~] = digitalElevationModel.loadTriaxialLunarDem( ...
    string(config.demFile),config.moonRadiusKm,24,48);

domainSouthDeg = -90;
domainNorthDeg = -75;
longitudeDeg = linspace(0,360,721);
latitudeDeg = linspace(domainSouthDeg,domainNorthDeg,301);
[longitudeMeshDeg,latitudeMeshDeg] = meshgrid(longitudeDeg,latitudeDeg);

elevationKm = double(demInterpolant( ...
    deg2rad(latitudeMeshDeg),deg2rad(longitudeMeshDeg)));
finiteElevationKm = elevationKm(isfinite(elevationKm));
assert(~isempty(finiteElevationKm), ...
    "The final lunar DEM produced no finite samples over the LSP domain.");
elevationLimitsKm = [min(finiteElevationKm),max(finiteElevationKm)];

% Completed CLPS south-polar landings.
completedLatitudeDeg = [-80.1277;-84.7754];
completedLongitudeDeg = [1.4357;29.1264];

% Mons Mouton planned/completed region.
monsLatitudeSouthDeg = -86.22;
monsLatitudeNorthDeg = -83.30;
monsLongitudeWestDeg = 11.67;
monsLongitudeEastDeg = 53.03;

% Schrodinger Basin optional regional overlap.
schrodingerLatitudeSouthDeg = -79.95;
schrodingerLatitudeNorthDeg = domainNorthDeg;
schrodingerLongitudeWestDeg = 112.33;
schrodingerLongitudeEastDeg = 153.44;

% Representative point for the LSP-wide planned-anchor group.
lspAnchorLatitudeDeg = domainNorthDeg;
lspAnchorLongitudeDeg = 315;

theme = struct( ...
    "backgroundColor",[1 1 1], ...
    "textColor",style.textColor, ...
    "boxColor",[1 1 1], ...
    "boxEdgeColor",[0.62 0.62 0.64], ...
    "boundaryColor",style.boundaryColor, ...
    "completedColor",style.redColor, ...
    "plannedColor",style.magentaColor, ...
    "optionalColor",style.orangeColor, ...
    "markerEdgeColor",[1 1 1]);

fontName = style.fontName;
siteFontSize = 14;
calloutFontSize = 14;
coordinateFontSize = 14;
boundaryFontSize = 14;
legendFontSize = 14;
colorbarFontSize = 14;

% Larger source canvas keeps the detailed callout text readable after the
% figure is reduced to conference-paper width.
figureWidth = 11.5;
figureHeight = 7.0;
fig = figure("Name","CLPS deployment context and restricted-domain detail", ...
    "Color",theme.backgroundColor,"Units","inches", ...
    "Position",[0.5 0.5 figureWidth figureHeight], ...
    "Renderer","opengl");
fig.InvertHardcopy = "off";

mapAxesPosition = [0.055 0.17 0.755 0.76];
ax = axes(fig,"Position",mapAxesPosition);
hold(ax,"on");
ax.Color = theme.backgroundColor;
ax.FontName = fontName;
ax.SortMethod = "childorder";

polarDistanceKm = config.moonRadiusKm .* deg2rad(90 + latitudeMeshDeg);
xKm = polarDistanceKm .* sind(longitudeMeshDeg);
yKm = polarDistanceKm .* cosd(longitudeMeshDeg);
outerRadiusKm = config.moonRadiusKm*deg2rad(15);

surf(ax,xKm,yKm,zeros(size(xKm)),elevationKm, ...
    "EdgeColor","none","FaceColor","interp");
view(ax,2);
colormap(ax,turbo(256));
clim(ax,elevationLimitsKm);

% Restricted-domain boundary. Standard plot grids are intentionally omitted.
circleAngleDeg = linspace(0,360,721);
xBoundary = outerRadiusKm*sind(circleAngleDeg);
yBoundary = outerRadiusKm*cosd(circleAngleDeg);
plot(ax,xBoundary,yBoundary, ...
    "Color",theme.boundaryColor,"LineWidth",2.6);

% Cardinal longitude labels remain as geographic references without grid lines.
longitudeLabelRadiusKm = outerRadiusKm + 24;
longitudeGridDeg = [0 90 180 270];
longitudeLabelText = ["0^{\circ}E","90^{\circ}E","180^{\circ}E","270^{\circ}E"];
for longitudeIndex = 1:numel(longitudeGridDeg)
    longitudeValue = longitudeGridDeg(longitudeIndex);
    text(ax,longitudeLabelRadiusKm*sind(longitudeValue), ...
        longitudeLabelRadiusKm*cosd(longitudeValue), ...
        longitudeLabelText(longitudeIndex), ...
        "Interpreter","tex","Color",theme.textColor, ...
        "FontName",fontName,"FontSize",coordinateFontSize, ...
        "FontWeight","bold","BackgroundColor",theme.boxColor, ...
        "Margin",1.2,"HorizontalAlignment","center", ...
        "VerticalAlignment","middle");
end

% Latitude labels from the original figure are retained without dashed rings.
latitudeLabelLongitudeDeg = 225;
for latitudeValue = [-85 -80]
    radiusKm = config.moonRadiusKm*deg2rad(90 + latitudeValue);
    text(ax,radiusKm*sind(latitudeLabelLongitudeDeg)-8, ...
        radiusKm*cosd(latitudeLabelLongitudeDeg)+7, ...
        sprintf("%d^{\\circ}S",abs(latitudeValue)), ...
        "Interpreter","tex","Color",theme.textColor, ...
        "FontName",fontName,"FontSize",coordinateFontSize, ...
        "FontWeight","bold","BackgroundColor",theme.boxColor, ...
        "Margin",1.2,"HorizontalAlignment","right", ...
        "VerticalAlignment","middle");
end

plot(ax,0,0,".","Color",theme.textColor,"MarkerSize",14);
text(ax,-18,-17,"South Pole", ...
    "Color",theme.textColor,"FontName",fontName, ...
    "FontSize",coordinateFontSize,"FontWeight","bold", ...
    "BackgroundColor",theme.boxColor,"Margin",1.3, ...
    "HorizontalAlignment","right","VerticalAlignment","top");

boundaryLabelY = -outerRadiusKm - 55;
text(ax,0,boundaryLabelY,"75^{\circ}S restricted-domain boundary", ...
    "Interpreter","tex","Color",theme.boundaryColor, ...
    "FontName",fontName,"FontSize",boundaryFontSize, ...
    "FontWeight","bold","BackgroundColor",theme.boxColor, ...
    "Margin",1.3,"HorizontalAlignment","center", ...
    "VerticalAlignment","top");

% Regions and mission markers.
[monsX,monsY] = rectangularPolarRegion( ...
    monsLatitudeSouthDeg,monsLatitudeNorthDeg, ...
    monsLongitudeWestDeg,monsLongitudeEastDeg,config.moonRadiusKm);
monsHandle = patch(ax,monsX,monsY,theme.plannedColor, ...
    "FaceAlpha",0.17,"EdgeColor",theme.plannedColor,"LineWidth",2.6, ...
    "DisplayName","Planned LSP anchor region");

[schX,schY] = rectangularPolarRegion( ...
    schrodingerLatitudeSouthDeg,schrodingerLatitudeNorthDeg, ...
    schrodingerLongitudeWestDeg,schrodingerLongitudeEastDeg,config.moonRadiusKm);
schHandle = patch(ax,schX,schY,theme.optionalColor, ...
    "FaceAlpha",0.16,"EdgeColor",theme.optionalColor,"LineWidth",2.4, ...
    "DisplayName","Optional regional overlap");

[completedX,completedY] = polarCoordinates( ...
    completedLatitudeDeg,completedLongitudeDeg,config.moonRadiusKm);
completedHandle = scatter(ax,completedX,completedY,86,"o", ...
    "MarkerFaceColor",theme.backgroundColor, ...
    "MarkerEdgeColor",theme.completedColor,"LineWidth",2.2, ...
    "DisplayName","Completed landing");

[lspAnchorX,lspAnchorY] = polarCoordinates( ...
    lspAnchorLatitudeDeg,lspAnchorLongitudeDeg,config.moonRadiusKm);
plannedHandle = scatter(ax,lspAnchorX,lspAnchorY,92,"d", ...
    "MarkerFaceColor",theme.plannedColor, ...
    "MarkerEdgeColor",theme.markerEdgeColor,"LineWidth",1.0, ...
    "DisplayName","Planned LSP anchor");

text(ax,completedX(2)+16,completedY(2)-18,"IM-2", ...
    "Color",theme.textColor,"FontName",fontName, ...
    "FontSize",siteFontSize,"FontWeight","bold", ...
    "BackgroundColor",theme.boxColor,"Margin",1.3, ...
    "HorizontalAlignment","left","VerticalAlignment","top");

% Detailed mission callouts restored from the original manuscript figure.
im1TextPosition = [-900,210];
im1ArrowStart = [-540,210];
drawDataArrow(ax,im1ArrowStart,[completedX(1),completedY(1)], ...
    theme.completedColor,2.0);
text(ax,im1TextPosition(1),im1TextPosition(2), ...
    {"IM-1 / TO2-IM","Completed - Near Malapert A"}, ...
    "Color",theme.textColor,"FontName",fontName, ...
    "FontSize",calloutFontSize,"FontWeight","bold", ...
    "BackgroundColor",theme.boxColor,"EdgeColor",theme.boxEdgeColor, ...
    "Margin",3.0,"HorizontalAlignment","left", ...
    "VerticalAlignment","middle");

lspTextPosition = [-900,485];
lspArrowStart = [-540,430];
drawDataArrow(ax,lspArrowStart,[lspAnchorX,lspAnchorY], ...
    theme.plannedColor,2.0);
text(ax,lspTextPosition(1),lspTextPosition(2), ...
    {"LSP-wide planned anchors", ...
     "Blue Moon MK1 / CT-3", ...
     "Blue Ghost 4 / CS-6", ...
     "Nova-D / CT-4"}, ...
    "Color",theme.textColor,"FontName",fontName, ...
    "FontSize",calloutFontSize,"FontWeight","bold", ...
    "BackgroundColor",theme.boxColor,"EdgeColor",theme.boxEdgeColor, ...
    "Margin",3.0,"HorizontalAlignment","left", ...
    "VerticalAlignment","middle");

monsAnchor = [mean(monsX),mean(monsY)];
monsTextPosition = [545,475];
monsArrowStart = [535,390];
drawDataArrow(ax,monsArrowStart,monsAnchor,theme.plannedColor,2.0);
text(ax,monsTextPosition(1),monsTextPosition(2), ...
    {"Mons Mouton", ...
     "Completed: IM-2 / PRIME-1", ...
     "Planned: Griffin / TO20A", ...
     "Planned: IM-4 / CP-22"}, ...
    "Color",theme.textColor,"FontName",fontName, ...
    "FontSize",calloutFontSize,"FontWeight","bold", ...
    "BackgroundColor",theme.boxColor,"EdgeColor",theme.boxEdgeColor, ...
    "Margin",3.0,"HorizontalAlignment","left", ...
    "VerticalAlignment","middle");

schAnchor = [mean(schX),mean(schY)];
schTextPosition = [545,-300];
schArrowStart = [530,-245];
drawDataArrow(ax,schArrowStart,schAnchor,theme.optionalColor,2.0);
text(ax,schTextPosition(1),schTextPosition(2), ...
    {"Schrodinger Basin", ...
     "SERIES-2 / CP-12 - planned", ...
     "Optional LSP anchor"}, ...
    "Color",theme.textColor,"FontName",fontName, ...
    "FontSize",calloutFontSize,"FontWeight","bold", ...
    "BackgroundColor",theme.boxColor,"EdgeColor",theme.boxEdgeColor, ...
    "Margin",3.0,"HorizontalAlignment","left", ...
    "VerticalAlignment","middle");

% Current-paper context: primary optimization is the complete southern
% hemisphere, while this detailed view shows the matched south-polar region.
text(ax,-965,-515, ...
    {"Primary design domain: southern hemisphere", ...
     "Detailed CLPS context shown for 90^{\circ}S--75^{\circ}S"}, ...
    "Interpreter","tex","Color",theme.textColor, ...
    "FontName",fontName,"FontSize",13,"FontWeight","bold", ...
    "BackgroundColor",theme.boxColor,"EdgeColor",theme.boxEdgeColor, ...
    "Margin",2.5,"HorizontalAlignment","left", ...
    "VerticalAlignment","middle");

axis(ax,"equal");
axis(ax,"off");
xlim(ax,[-1000 1000]);
ylim(ax,[-650 650]);

colorbarHandle = colorbar(ax,"eastoutside");
colorbarHandle.Units = "normalized";
colorbarHandle.Position = [0.865 0.19 0.020 0.65];
colorbarHandle.FontName = fontName;
colorbarHandle.FontSize = colorbarFontSize;
colorbarHandle.FontWeight = "bold";
colorbarHandle.Color = theme.textColor;
colorbarHandle.Label.String = "DEM elevation (km)";
colorbarHandle.Label.FontName = fontName;
colorbarHandle.Label.FontSize = colorbarFontSize;
colorbarHandle.Label.FontWeight = "bold";
colorbarHandle.Label.Color = theme.textColor;

% Restore map position after colorbar allocation.
ax.Position = mapAxesPosition;

% Specific exception to the general results-figure legend rule: the original
% geographic figure uses a centered legend beneath the full composition.
legendHandle = legend(ax, ...
    [completedHandle plannedHandle monsHandle schHandle], ...
    "Completed landing","Planned LSP anchor", ...
    "Planned LSP anchor region","Optional regional overlap", ...
    "Orientation","horizontal","NumColumns",4,"Box","on");
legendHandle.Units = "normalized";
legendHandle.Position = [0.09 0.025 0.82 0.075];
legendHandle.FontName = fontName;
legendHandle.FontSize = legendFontSize;
legendHandle.FontWeight = "bold";
legendHandle.TextColor = theme.textColor;
legendHandle.Color = theme.boxColor;
legendHandle.EdgeColor = theme.boxEdgeColor;
legendHandle.ItemTokenSize = [18 10];

outputFile = fullfile(config.outputDirectory, ...
    "CLPS_Southern_Hemisphere_Design_Domain.eps");
exportManuscriptFigure(fig,string(outputFile),figureWidth,figureHeight);

plotInfo = struct("figure",fig,"outputFile",string(outputFile));
end

function drawDataArrow(ax,startPoint,endPoint,color,lineWidth)
quiver(ax,startPoint(1),startPoint(2), ...
    endPoint(1)-startPoint(1),endPoint(2)-startPoint(2),0, ...
    "Color",color,"LineWidth",lineWidth,"MaxHeadSize",0.70, ...
    "AutoScale","off","HandleVisibility","off");
end

function [xKm,yKm] = polarCoordinates(latitudeDeg,longitudeDeg,moonRadiusKm)
radiusKm = moonRadiusKm.*deg2rad(90+latitudeDeg);
xKm = radiusKm.*sind(longitudeDeg);
yKm = radiusKm.*cosd(longitudeDeg);
end

function [xKm,yKm] = rectangularPolarRegion( ...
    latitudeSouthDeg,latitudeNorthDeg,longitudeWestDeg,longitudeEastDeg,moonRadiusKm)
numberOfSamples = 120;
longitudeSouth = linspace(longitudeWestDeg,longitudeEastDeg,numberOfSamples);
latitudeEast = linspace(latitudeSouthDeg,latitudeNorthDeg,numberOfSamples);
longitudeNorth = linspace(longitudeEastDeg,longitudeWestDeg,numberOfSamples);
latitudeWest = linspace(latitudeNorthDeg,latitudeSouthDeg,numberOfSamples);
latitudeBoundary = [ ...
    latitudeSouthDeg*ones(1,numberOfSamples), ...
    latitudeEast, ...
    latitudeNorthDeg*ones(1,numberOfSamples), ...
    latitudeWest];
longitudeBoundary = [ ...
    longitudeSouth, ...
    longitudeEastDeg*ones(1,numberOfSamples), ...
    longitudeNorth, ...
    longitudeWestDeg*ones(1,numberOfSamples)];
[xKm,yKm] = polarCoordinates(latitudeBoundary,longitudeBoundary,moonRadiusKm);
end

function out = mergeStruct(defaults,override)
out = defaults;
fields = fieldnames(override);
for k = 1:numel(fields)
    out.(fields{k}) = override.(fields{k});
end
end
