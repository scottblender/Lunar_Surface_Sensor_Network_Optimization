    "PreserveAspectRatio","on");

fprintf("Exported: %s\n",moonCenteredFile);
fprintf("Exported: %s\n",sensorCenteredFile);
fprintf("plotReferenceFrameTransformations completed.\n");

%% Local plotting functions

function drawArrow2D( ...
    axesHandle,startPoint,endPoint,arrowColor, ...
    lineWidth,headLength,headWidth,lineStyle)

direction = endPoint - startPoint;
directionLength = norm(direction);

assert(directionLength > headLength, ...
    "The arrow is too short for the requested arrowhead.");

unitDirection = direction/directionLength;

normalDirection = [
   -unitDirection(2)
    unitDirection(1)
];

arrowBase = ...
    endPoint - headLength*unitDirection;

plot(axesHandle, ...
    [startPoint(1) arrowBase(1)], ...
    [startPoint(2) arrowBase(2)], ...
    "Color",arrowColor, ...
    "LineStyle",lineStyle, ...
    "LineWidth",lineWidth);

trianglePoints = [
    endPoint, ...
    arrowBase + 0.5*headWidth*normalDirection, ...
    arrowBase - 0.5*headWidth*normalDirection
];

patch(axesHandle, ...
    trianglePoints(1,:), ...
    trianglePoints(2,:), ...
    arrowColor, ...
    "EdgeColor","none");

end

function drawArrowHead2D( ...
    axesHandle,endPoint,direction,arrowColor, ...
    headLength,headWidth)

unitDirection = ...
    direction/norm(direction);

normalDirection = [
   -unitDirection(2)
    unitDirection(1)
];

arrowBase = ...
    endPoint - headLength*unitDirection;

trianglePoints = [
    endPoint, ...
    arrowBase + 0.5*headWidth*normalDirection, ...
    arrowBase - 0.5*headWidth*normalDirection
];

patch(axesHandle, ...
    trianglePoints(1,:), ...
    trianglePoints(2,:), ...
    arrowColor, ...
    "EdgeColor","none");

end