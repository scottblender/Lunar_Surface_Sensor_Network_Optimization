rhoLabelPosition = ...
    sensorPosition + ...
    0.57*relativePositionVector;

text(sensorCenteredAxes, ...
    rhoLabelPosition(1) + 0.09, ...
    rhoLabelPosition(2), ...
    "\rho_T", ...
    "Interpreter","tex", ...
    "Color",relativePositionColor, ...
    "FontName",fontName, ...
    "FontSize",axisLabelFontSize, ...
    "FontWeight","bold");

%% Export both EPS subfigures

drawnow;

exportgraphics( ...
    moonCenteredAxes, ...
