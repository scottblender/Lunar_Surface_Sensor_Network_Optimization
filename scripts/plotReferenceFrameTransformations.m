    localAxisLength*northDirection;

drawArrow2D( ...
    sensorCenteredAxes, ...
    sensorPosition, ...
    northEnd, ...
    northColor, ...
    localLineWidth, ...
    localArrowLength, ...
    localArrowWidth, ...
    "-");

northLabelPosition = ...
    sensorPosition + 0.70*northDirection;

text(sensorCenteredAxes, ...
    northLabelPosition(1), ...
    northLabelPosition(2), ...
    "N", ...
    "Color",northColor, ...
    "FontName",fontName, ...
    "FontSize",axisLabelFontSize, ...
    "FontWeight","bold", ...
    "HorizontalAlignment","center");

%% Draw the up axis

upEnd = ...
    sensorPosition + ...
    localAxisLength*upDirection;

drawArrow2D( ...
    sensorCenteredAxes, ...
    sensorPosition, ...
    upEnd, ...
    upColor, ...
    localLineWidth, ...
    localArrowLength, ...
    localArrowWidth, ...
    "-");

upLabelPosition = ...
    sensorPosition + 0.70*upDirection;

text(sensorCenteredAxes, ...
    upLabelPosition(1), ...
    upLabelPosition(2), ...
    "U", ...
    "Color",upColor, ...
    "FontName",fontName, ...
    "FontSize",axisLabelFontSize, ...
    "FontWeight","bold", ...
    "HorizontalAlignment","center");

%% Define and plot an example RSO

rsoPosition = [0.80;1.50];

relativePositionVector = ...
    rsoPosition - sensorPosition;

drawArrow2D( ...
    sensorCenteredAxes, ...
    sensorPosition, ...
    rsoPosition, ...
    relativePositionColor, ...
    2.2, ...
    0.095, ...
    0.072, ...
