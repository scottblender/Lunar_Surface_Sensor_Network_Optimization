%% Local helpers

function [representativeIndices,scaleOutlierIndex] = ...
    selectRepresentativeRsos(rsoCatalog,maxRadiusByObjectKm)
% Select a compact set spanning orbital size and inclination.

numberOfObjects = numel(maxRadiusByObjectKm);
allIndices = (1:numberOfObjects).';
scaleOutlierIndex = NaN;
availableIndices = allIndices;

if numberOfObjects >= 4
    [sortedRadii,sortedRadiusIndices] = sort(maxRadiusByObjectKm(:));
    if sortedRadii(end) > 1.25*sortedRadii(end-1)
        scaleOutlierIndex = sortedRadiusIndices(end);
        availableIndices(availableIndices == scaleOutlierIndex) = [];
    end
end

if isempty(availableIndices)
    availableIndices = allIndices;
    scaleOutlierIndex = NaN;
end

representativeIndices = zeros(0,1);

hasCatalog = ...
    ~isempty(rsoCatalog) && ...
    height(rsoCatalog) >= numberOfObjects;

if hasCatalog && ...
        all(ismember(["ApoapsisAltitudeKm","InclinationRad"], ...
        string(rsoCatalog.Properties.VariableNames)))

    apoapsis = rsoCatalog.ApoapsisAltitudeKm;
    inclination = rsoCatalog.InclinationRad;

    [~,apoOrderLocal] = sort(apoapsis(availableIndices));
    apoOrder = availableIndices(apoOrderLocal);
    apoRanks = unique(round(linspace(1,numel(apoOrder),3)));
    representativeIndices = apoOrder(apoRanks);

    [~,minimumInclinationLocal] = min(inclination(availableIndices));
    [~,polarInclinationLocal] = min(abs(inclination(availableIndices)-pi/2));
    [~,maximumInclinationLocal] = max(inclination(availableIndices));

    representativeIndices = unique([ ...
        representativeIndices(:)
        availableIndices(minimumInclinationLocal)
        availableIndices(polarInclinationLocal)
        availableIndices(maximumInclinationLocal)],"stable");
else
    rankIndices = unique(round(linspace(1,numel(availableIndices),6)));
    representativeIndices = availableIndices(rankIndices);
end

maximumRepresentatives = min(6,numel(availableIndices));

if numel(representativeIndices) > maximumRepresentatives
    representativeIndices = representativeIndices(1:maximumRepresentatives);
end

if numel(representativeIndices) < maximumRepresentatives
    fillRanks = unique(round( ...
        linspace(1,numel(availableIndices),maximumRepresentatives)));
    fillIndices = availableIndices(fillRanks);
    representativeIndices = unique( ...
        [representativeIndices(:);fillIndices(:)],"stable");
    representativeIndices = representativeIndices(1:maximumRepresentatives);
end

end

function [classIndex,color,label] = trajectoryClass(rsoCatalog,objectIndex,style)

inclinationDeg = NaN;

if ~isempty(rsoCatalog) && ...
        height(rsoCatalog) >= objectIndex && ...
        ismember("InclinationRad",string(rsoCatalog.Properties.VariableNames))
    inclinationDeg = rad2deg(rsoCatalog.InclinationRad(objectIndex));
end

if ~isfinite(inclinationDeg)
    classIndex = 1;
    color = style.progradeColor;
    label = "RSO";
elseif abs(inclinationDeg-90) <= 15
    classIndex = 2;
    color = style.polarColor;
    label = "Near-polar";
elseif inclinationDeg < 90
    classIndex = 1;
    color = style.progradeColor;
    label = "Prograde";
else
    classIndex = 3;
    color = style.retrogradeColor;
    label = "Retrograde";
end

end

function labelText = representativeRsoLabel(rsoCatalog,objectIndex)

labelText = sprintf("RSO %02d",objectIndex);

if isempty(rsoCatalog) || height(rsoCatalog) < objectIndex
    return
end

variableNames = string(rsoCatalog.Properties.VariableNames);

if all(ismember(["PeriapsisAltitudeKm","InclinationRad"],variableNames))
    labelText = sprintf( ...
        "RSO %02d: %.0f km, i = %.0f^{\\circ}", ...
        objectIndex, ...
        rsoCatalog.PeriapsisAltitudeKm(objectIndex), ...
        rad2deg(rsoCatalog.InclinationRad(objectIndex)));
elseif ismember("Name",variableNames)
    labelText = string(rsoCatalog.Name(objectIndex));
end

end

