function figureInfo = plotOptimizationPilotResults(studyState)
% PLOTOPTIMIZATIONPILOTRESULTS Plot completed 10 x 1200-FE pilot results.
%
% Figures:
%   1. Overall-best optimized sensor locations in the south-polar domain.
%   2. Representative RSO trajectories in the Moon-rotating (MR) frame.
%   3. Publication-style best-so-far objective convergence versus FE.
%
% The optimization and EKF states are stored and propagated in MCI. Figure 2
% transforms those histories to MR only for visualization so the lunar
% surface and optimized sensor locations remain fixed in the plotted frame.
%
% If studyState is omitted, the newest completed 10 x 1200-FE pilot is used.

arguments
    studyState (1,1) struct = struct()
end

%% Project paths and study loading

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
resultsDirectory = fullfile(projectRoot,"results");

if isempty(fieldnames(studyState))
    summaryFile = findLatestPilotSummary(resultsDirectory);
    loadedStudy = load(summaryFile,"studyState");
    assert(isfield(loadedStudy,"studyState"), ...
        "Pilot summary does not contain studyState.");
    studyState = loadedStudy.studyState;
end

assert(isfield(studyState,"validation") && ...
    isfield(studyState.validation,"overallBest"), ...
    "studyState does not contain overall-best EKF validation results.");
assert(isfield(studyState,"overallBestSensorIndices"), ...
    "studyState does not contain the overall-best sensor network.");
assert(isfield(studyState,"studyDirectory"), ...
    "studyState does not identify its output directory.");

validation = studyState.validation.overallBest;

databaseFile = string(studyState.config.databaseFile);
assert(isfile(databaseFile), ...
    "Optimization database was not found: %s",databaseFile);

databaseData = load(databaseFile,"database");
assert(isfield(databaseData,"database"), ...
    "Optimization database MAT file does not contain database.");
database = databaseData.database;

%% Shared styling

style = struct();
style.fontName = "Arial";
style.axisFontSize = 11;
style.labelFontSize = 12;
style.annotationFontSize = 11;
style.legendFontSize = 10.5;

style.darkBackground = [0.015 0.020 0.030];
style.darkText = [0.96 0.97 0.99];
style.darkMuted = [0.72 0.75 0.80];
style.darkGrid = [0.16 0.18 0.22];
style.darkBox = [0.035 0.042 0.055];
style.darkBoxEdge = [0.36 0.40 0.46];

style.candidateColor = [0.28 0.30 0.35];
style.boundaryColor = [0.12 0.82 0.95];
style.sensorColor = [1.00 0.27 0.23];
style.moonColor = [0.62 0.62 0.64];

style.progradeColor = [0.05 0.72 0.52];
style.polarColor = [0.98 0.67 0.08];
style.retrogradeColor = [0.92 0.25 0.24];

style.lightBackground = [1 1 1];
style.lightText = [0.12 0.12 0.12];
style.lightGrid = [0.86 0.86 0.86];
style.runColor = [0.68 0.68 0.68];
style.meanColor = [0.08 0.27 0.52];
style.bandColor = [0.88 0.91 0.95];

style.exportWidthInches = 6.50;
style.sensorHeightInches = 6.50;
style.rsoHeightInches = 6.50;
style.convergenceHeightInches = 4.25;
style.exportPaddingInches = 0.25;

%% Output directory

figureDirectory = fullfile(string(studyState.studyDirectory),"figures");
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end

sensorOutputFile = fullfile( ...
    figureDirectory,"optimized_sensor_network.eps");
rsoOutputFile = fullfile( ...
    figureDirectory,"representative_rso_geometry.eps");
convergenceOutputFile = fullfile( ...
    figureDirectory,"optimization_convergence.eps");

%% Common geometry

moonRadiusKm = database.config.moon.radiusKm;

candidateLatitudeDeg = ...
    rad2deg(database.candidates.latitudesRad(:));
candidateLongitudeDeg = ...
    rad2deg(database.candidates.longitudesRad(:));

bestSensorIndices = studyState.overallBestSensorIndices(:);
bestSensorLatitudeDeg = candidateLatitudeDeg(bestSensorIndices);
bestSensorLongitudeDeg = candidateLongitudeDeg(bestSensorIndices);

%% Figure 1: optimized sensor locations

sensorFigure = figure( ...
    "Name","Optimized Sensor Network", ...
    "Color",style.darkBackground, ...
    "Units","inches", ...
    "Position",[1 1 style.exportWidthInches style.sensorHeightInches], ...
    "Renderer","painters");
sensorFigure.InvertHardcopy = "off";

sensorLayout = tiledlayout( ...
    sensorFigure,1,1, ...
    "TileSpacing","compact", ...
    "Padding","compact");

sensorAxes = nexttile(sensorLayout,1);
hold(sensorAxes,"on");
axis(sensorAxes,"equal");
axis(sensorAxes,"off");
sensorAxes.Color = style.darkBackground;
sensorAxes.FontName = style.fontName;
sensorAxes.FontSize = style.axisFontSize;

candidateRadiusKm = ...
    moonRadiusKm .* deg2rad(90.0 + candidateLatitudeDeg);
candidateXKm = candidateRadiusKm .* sind(candidateLongitudeDeg);
candidateYKm = candidateRadiusKm .* cosd(candidateLongitudeDeg);

candidateHandle = scatter( ...
    sensorAxes,candidateXKm,candidateYKm,7,style.candidateColor,"filled", ...
    "DisplayName","Candidates");

circleAngleDeg = linspace(0,360,721);
latitudeGridDeg = [-85 -80 -75];
boundaryHandle = gobjects(1);

for latitudeIndex = 1:numel(latitudeGridDeg)
    currentLatitudeDeg = latitudeGridDeg(latitudeIndex);
    currentRadiusKm = moonRadiusKm*deg2rad(90.0 + currentLatitudeDeg);
    circleXKm = currentRadiusKm*sind(circleAngleDeg);
    circleYKm = currentRadiusKm*cosd(circleAngleDeg);

    if currentLatitudeDeg == -75
        boundaryHandle = plot( ...
            sensorAxes,circleXKm,circleYKm, ...
            "Color",style.boundaryColor, ...
            "LineWidth",2.1, ...
            "DisplayName","75^{\circ}S boundary");
    else
        plot( ...
            sensorAxes,circleXKm,circleYKm,"--", ...
            "Color",style.darkGrid, ...
            "LineWidth",0.9, ...
            "HandleVisibility","off");
    end
end

outerRadiusKm = moonRadiusKm*deg2rad(15.0);
longitudeGridDeg = [0 90 180 270];

for longitudeIndex = 1:numel(longitudeGridDeg)
    currentLongitudeDeg = longitudeGridDeg(longitudeIndex);
    radialDistanceKm = [0 outerRadiusKm];

    plot( ...
        sensorAxes, ...
        radialDistanceKm*sind(currentLongitudeDeg), ...
        radialDistanceKm*cosd(currentLongitudeDeg), ...
        "--", ...
        "Color",style.darkGrid, ...
        "LineWidth",0.9, ...
        "HandleVisibility","off");
end

longitudeLabelRadiusKm = outerRadiusKm + 34;
longitudeLabelText = [ ...
    "0^{\circ}E" ...
    "90^{\circ}E" ...
    "180^{\circ}E" ...
    "270^{\circ}E"];

for longitudeIndex = 1:numel(longitudeGridDeg)
    currentLongitudeDeg = longitudeGridDeg(longitudeIndex);

    text( ...
        sensorAxes, ...
        longitudeLabelRadiusKm*sind(currentLongitudeDeg), ...
        longitudeLabelRadiusKm*cosd(currentLongitudeDeg), ...
        longitudeLabelText(longitudeIndex), ...
        "Interpreter","tex", ...
        "Color",style.darkText, ...
        "FontName",style.fontName, ...
        "FontSize",style.annotationFontSize, ...
        "FontWeight","bold", ...
        "BackgroundColor",style.darkBox, ...
        "EdgeColor","none", ...
        "Margin",1.5, ...
        "HorizontalAlignment","center", ...
        "VerticalAlignment","middle");
end

latitudeLabelLongitudeDeg = 225;
for latitudeIndex = 1:2
    currentLatitudeDeg = latitudeGridDeg(latitudeIndex);
    currentRadiusKm = moonRadiusKm*deg2rad(90.0 + currentLatitudeDeg);

    text( ...
        sensorAxes, ...
        currentRadiusKm*sind(latitudeLabelLongitudeDeg) - 7, ...
        currentRadiusKm*cosd(latitudeLabelLongitudeDeg) + 7, ...
        sprintf("%d^{\\circ}S",abs(currentLatitudeDeg)), ...
        "Interpreter","tex", ...
        "Color",style.darkText, ...
        "FontName",style.fontName, ...
        "FontSize",style.annotationFontSize, ...
        "FontWeight","bold", ...
        "BackgroundColor",style.darkBox, ...
        "EdgeColor","none", ...
        "Margin",1.5, ...
        "HorizontalAlignment","right", ...
        "VerticalAlignment","middle");
end

scatter( ...
    sensorAxes,0,0,28,".", ...
    "MarkerEdgeColor",style.darkText, ...
    "HandleVisibility","off");

text( ...
    sensorAxes,-16,-16,"90^{\circ}S", ...
    "Interpreter","tex", ...
    "Color",style.darkText, ...
    "FontName",style.fontName, ...
    "FontSize",style.annotationFontSize, ...
    "FontWeight","bold", ...
    "BackgroundColor",style.darkBox, ...
    "EdgeColor","none", ...
    "Margin",1.5, ...
    "HorizontalAlignment","right", ...
    "VerticalAlignment","top");

bestSensorRadiusKm = ...
    moonRadiusKm .* deg2rad(90.0 + bestSensorLatitudeDeg);
bestSensorXKm = bestSensorRadiusKm .* sind(bestSensorLongitudeDeg);
bestSensorYKm = bestSensorRadiusKm .* cosd(bestSensorLongitudeDeg);

sensorHandle = scatter( ...
    sensorAxes,bestSensorXKm,bestSensorYKm,115,"o", ...
    "MarkerFaceColor",style.sensorColor, ...
    "MarkerEdgeColor",style.darkText, ...
    "LineWidth",1.4, ...
    "DisplayName","Optimized sensors");

for sensorIndex = 1:numel(bestSensorIndices)
    sensorPosition = [bestSensorXKm(sensorIndex);bestSensorYKm(sensorIndex)];
    sensorPositionNorm = norm(sensorPosition);

    if sensorPositionNorm > 1
        labelDirection = sensorPosition/sensorPositionNorm;
    else
        labelDirection = [1;0];
    end

    labelPosition = sensorPosition + 26*labelDirection;

    text( ...
        sensorAxes,labelPosition(1),labelPosition(2), ...
        sprintf("S%d",sensorIndex), ...
        "Color",style.darkText, ...
        "FontName",style.fontName, ...
        "FontSize",style.annotationFontSize, ...
        "FontWeight","bold", ...
        "BackgroundColor",style.darkBox, ...
        "EdgeColor",style.darkBoxEdge, ...
        "Margin",2.0, ...
        "HorizontalAlignment","center", ...
        "VerticalAlignment","middle");
end

sensorLimitKm = outerRadiusKm + 82;
xlim(sensorAxes,[-sensorLimitKm sensorLimitKm]);
ylim(sensorAxes,[-sensorLimitKm sensorLimitKm]);

sensorLegend = legend( ...
    sensorAxes, ...
    [candidateHandle boundaryHandle sensorHandle], ...
    "Candidates", ...
    "75^{\circ}S boundary", ...
    "Optimized sensors", ...
    "Orientation","horizontal");
styleDarkLegend(sensorLegend,style);
sensorLegend.Layout.Tile = "south";

%% Figure 2: representative RSO trajectories in MR

truthStateHistoriesMci = validation.truthStateHistories;
trajectoryTimes = validation.times(:);

assert(ndims(truthStateHistoriesMci) == 3 && ...
    size(truthStateHistoriesMci,1) == 6, ...
    "Validation truth-state histories have an unexpected size.");
assert(size(truthStateHistoriesMci,2) == numel(trajectoryTimes), ...
    "Validation trajectory times do not match truth histories.");
assert(all(isfinite(truthStateHistoriesMci),"all"), ...
    "RSO truth trajectories contain nonfinite values.");

numberOfObjects = size(truthStateHistoriesMci,3);
theta0Rad = database.config.moon.theta0Rad;
moonAngularRate = 2*pi/database.config.moon.siderealPeriodSeconds;

truthStateHistoriesMr = zeros(size(truthStateHistoriesMci));

for objectIndex = 1:numberOfObjects
    for timeIndex = 1:numel(trajectoryTimes)
        truthStateHistoriesMr(:,timeIndex,objectIndex) = ...
            referenceFrames.moonRotating( ...
                truthStateHistoriesMci(:,timeIndex,objectIndex), ...
                trajectoryTimes(timeIndex), ...
                theta0Rad, ...
                moonAngularRate, ...
                "fromInertial");
    end
end

radiusHistoriesKm = squeeze( ...
    sqrt(sum(truthStateHistoriesMr(1:3,:,:).^2,1)));
maxRadiusByObjectKm = max(radiusHistoriesKm,[],1);
[farthestRadiusKm,farthestObjectIndex] = max(maxRadiusByObjectKm);

if isfield(database,"rso") && isfield(database.rso,"catalog")
    rsoCatalog = database.rso.catalog;
else
    rsoCatalog = table();
end

[representativeIndices,scaleOutlierIndex] = ...
    selectRepresentativeRsos(rsoCatalog,maxRadiusByObjectKm);

representativePositionsKm = ...
    truthStateHistoriesMr(1:3,:,representativeIndices);

plotLimitKm = 1.10*max(abs(representativePositionsKm),[],"all");
plotLimitKm = max(plotLimitKm,4.0*moonRadiusKm);

rsoFigure = figure( ...
    "Name","Representative RSO Trajectories (MR)", ...
    "Color",style.darkBackground, ...
    "Units","inches", ...
    "Position",[1 1 style.exportWidthInches style.rsoHeightInches], ...
    "Renderer","opengl");
rsoFigure.InvertHardcopy = "off";

rsoAxes = axes( ...
    rsoFigure, ...
    "Units","normalized", ...
    "Position",[0.035 0.045 0.93 0.87]);
hold(rsoAxes,"on");
axis(rsoAxes,"equal");
axis(rsoAxes,"vis3d");
axis(rsoAxes,"off");
rsoAxes.Color = style.darkBackground;

[moonX,moonY,moonZ] = sphere(120);
moonHandle = surf( ...
    rsoAxes, ...
    moonRadiusKm*moonX, ...
    moonRadiusKm*moonY, ...
    moonRadiusKm*moonZ, ...
    "FaceColor",style.moonColor, ...
    "EdgeColor","none", ...
    "FaceAlpha",1.0, ...
    "AmbientStrength",0.38, ...
    "DiffuseStrength",0.75, ...
    "SpecularStrength",0.10, ...
    "DisplayName","Moon");

view(rsoAxes,36,19);
camproj(rsoAxes,"orthographic");
camlight(rsoAxes,"headlight");
camlight(rsoAxes,"right");
lighting(rsoAxes,"gouraud");

% Plot all in-scale trajectories lightly, then redraw selected trajectories
% with class colors and current-location markers.
contextHandles = gobjects(3,1);
contextCreated = false(3,1);

for objectIndex = 1:numberOfObjects
    if ismember(objectIndex,representativeIndices)
        continue
    end

    currentPositionKm = truthStateHistoriesMr(1:3,:,objectIndex);

    if max(abs(currentPositionKm),[],"all") > 1.02*plotLimitKm
        continue
    end

    [classIndex,currentColor,~] = ...
        trajectoryClass(rsoCatalog,objectIndex,style);
    fadedColor = blendColor(currentColor,style.darkBackground,0.28);

    plotHandle = plot3( ...
        rsoAxes, ...
        currentPositionKm(1,:), ...
        currentPositionKm(2,:), ...
        currentPositionKm(3,:), ...
        "Color",fadedColor, ...
        "LineWidth",0.8, ...
        "HandleVisibility","off");

    if ~contextCreated(classIndex)
        contextHandles(classIndex) = plotHandle;
        contextCreated(classIndex) = true;
    end
end

representativeHandles = gobjects(3,1);
representativeCreated = false(3,1);

for representativeNumber = 1:numel(representativeIndices)
    objectIndex = representativeIndices(representativeNumber);
    currentPositionKm = truthStateHistoriesMr(1:3,:,objectIndex);

    [classIndex,currentColor,~] = ...
        trajectoryClass(rsoCatalog,objectIndex,style);

    plotHandle = plot3( ...
        rsoAxes, ...
        currentPositionKm(1,:), ...
        currentPositionKm(2,:), ...
        currentPositionKm(3,:), ...
        "Color",currentColor, ...
        "LineWidth",1.9, ...
        "HandleVisibility","off");

    if ~representativeCreated(classIndex)
        representativeHandles(classIndex) = plotHandle;
        representativeCreated(classIndex) = true;
    end

    markerPositionKm = currentPositionKm(:,1);

    scatter3( ...
        rsoAxes, ...
        markerPositionKm(1), ...
        markerPositionKm(2), ...
        markerPositionKm(3), ...
        44,"o", ...
        "MarkerFaceColor",currentColor, ...
        "MarkerEdgeColor",currentColor, ...
        "HandleVisibility","off");

    labelDirection = markerPositionKm/max(norm(markerPositionKm),1);
    labelPositionKm = markerPositionKm + 0.035*plotLimitKm*labelDirection;

    text( ...
        rsoAxes, ...
        labelPositionKm(1), ...
        labelPositionKm(2), ...
        labelPositionKm(3), ...
        representativeRsoLabel(rsoCatalog,objectIndex), ...
        "Interpreter","tex", ...
        "Color",currentColor, ...
        "FontName",style.fontName, ...
        "FontSize",10.5, ...
        "FontWeight","bold", ...
        "HorizontalAlignment","left", ...
        "VerticalAlignment","middle");
end

% Optimized sensors are body-fixed, so their selenographic positions are
% directly consistent with the MR visualization.
sensorDisplayRadiusKm = moonRadiusKm + 18;
sensorXKm = sensorDisplayRadiusKm .* ...
    cosd(bestSensorLatitudeDeg).*cosd(bestSensorLongitudeDeg);
sensorYKm = sensorDisplayRadiusKm .* ...
    cosd(bestSensorLatitudeDeg).*sind(bestSensorLongitudeDeg);
sensorZKm = sensorDisplayRadiusKm .* sind(bestSensorLatitudeDeg);

rsoSensorHandle = scatter3( ...
    rsoAxes,sensorXKm,sensorYKm,sensorZKm,62,"o", ...
    "MarkerFaceColor",style.sensorColor, ...
    "MarkerEdgeColor",style.darkText, ...
    "LineWidth",1.2, ...
    "DisplayName","Optimized sensors");

for sensorIndex = 1:numel(bestSensorIndices)
    sensorPositionKm = ...
        [sensorXKm(sensorIndex);sensorYKm(sensorIndex);sensorZKm(sensorIndex)];
    sensorLabelPositionKm = 1.08*sensorPositionKm;

    text( ...
        rsoAxes, ...
        sensorLabelPositionKm(1), ...
        sensorLabelPositionKm(2), ...
        sensorLabelPositionKm(3), ...
        sprintf("S%d",sensorIndex), ...
        "Color",style.darkText, ...
        "FontName",style.fontName, ...
        "FontSize",9.5, ...
        "FontWeight","bold", ...
        "HorizontalAlignment","center");
end

xlim(rsoAxes,[-plotLimitKm plotLimitKm]);
ylim(rsoAxes,[-plotLimitKm plotLimitKm]);
zlim(rsoAxes,[-plotLimitKm plotLimitKm]);
daspect(rsoAxes,[1 1 1]);
pbaspect(rsoAxes,[1 1 1]);

% Compact MR triad and scale label.
triadOriginKm = [-0.79 -0.78 -0.70].'*plotLimitKm;
triadLengthKm = 0.18*plotLimitKm;
triadColor = blendColor(style.darkText,style.darkBackground,0.80);

quiver3(rsoAxes,triadOriginKm(1),triadOriginKm(2),triadOriginKm(3), ...
    triadLengthKm,0,0,0, ...
    "Color",triadColor,"LineWidth",1.35,"MaxHeadSize",0.45);
quiver3(rsoAxes,triadOriginKm(1),triadOriginKm(2),triadOriginKm(3), ...
    0,triadLengthKm,0,0, ...
    "Color",triadColor,"LineWidth",1.35,"MaxHeadSize",0.45);
quiver3(rsoAxes,triadOriginKm(1),triadOriginKm(2),triadOriginKm(3), ...
    0,0,triadLengthKm,0, ...
    "Color",triadColor,"LineWidth",1.35,"MaxHeadSize",0.45);

text(rsoAxes,triadOriginKm(1)+1.10*triadLengthKm, ...
    triadOriginKm(2),triadOriginKm(3),"x_{MR}", ...
    "Interpreter","tex","Color",style.darkText, ...
    "FontName",style.fontName,"FontSize",10.5,"FontWeight","bold");
text(rsoAxes,triadOriginKm(1), ...
    triadOriginKm(2)+1.10*triadLengthKm,triadOriginKm(3),"y_{MR}", ...
    "Interpreter","tex","Color",style.darkText, ...
    "FontName",style.fontName,"FontSize",10.5,"FontWeight","bold");
text(rsoAxes,triadOriginKm(1),triadOriginKm(2), ...
    triadOriginKm(3)+1.10*triadLengthKm,"z_{MR}", ...
    "Interpreter","tex","Color",style.darkText, ...
    "FontName",style.fontName,"FontSize",10.5,"FontWeight","bold");

scaleText = sprintf("Moon-rotating frame   |   1 div. \\approx %.0f km", ...
    plotLimitKm/4);
text(rsoAxes,-0.95*plotLimitKm,-0.92*plotLimitKm,-0.90*plotLimitKm, ...
    scaleText, ...
    "Interpreter","tex", ...
    "Color",style.darkMuted, ...
    "FontName",style.fontName, ...
    "FontSize",9.5, ...
    "FontWeight","bold");

legendHandles = moonHandle;
legendLabels = "Moon";

classLabels = ["Prograde RSOs","Near-polar RSOs","Retrograde RSOs"];
for classIndex = 1:3
    if representativeCreated(classIndex)
        legendHandles(end+1) = representativeHandles(classIndex); %#ok<AGROW>
        legendLabels(end+1) = classLabels(classIndex); %#ok<AGROW>
    elseif contextCreated(classIndex)
        legendHandles(end+1) = contextHandles(classIndex); %#ok<AGROW>
        legendLabels(end+1) = classLabels(classIndex); %#ok<AGROW>
    end
end

legendHandles(end+1) = rsoSensorHandle;
legendLabels(end+1) = "Optimized sensors";

rsoLegend = legend( ...
    rsoAxes,legendHandles,cellstr(legendLabels), ...
    "Orientation","horizontal", ...
    "NumColumns",2, ...
    "Units","normalized");
styleDarkLegend(rsoLegend,style);
rsoLegend.Position = [0.19 0.895 0.62 0.085];

%% Figure 3: publication-style convergence versus function evaluations

referenceFe = studyState.runStates{1}.history.fe(:);
numberOfRuns = studyState.numberOfRuns;
numberOfHistoryPoints = numel(referenceFe);
objectiveHistory = NaN(numberOfHistoryPoints,numberOfRuns);

for runIndex = 1:numberOfRuns
    currentRun = studyState.runStates{runIndex};
    assert(isequal(currentRun.history.fe(:),referenceFe), ...
        "Run %d does not share the common FE grid.",runIndex);
    objectiveHistory(:,runIndex) = currentRun.history.bestJ(:);
end

meanObjective = mean(objectiveHistory,2);
stdObjective = std(objectiveHistory,0,2);
lowerSigma = meanObjective - stdObjective;
upperSigma = meanObjective + stdObjective;

convergenceFigure = figure( ...
    "Name","Optimization Convergence", ...
    "Color",style.lightBackground, ...
    "Units","inches", ...
    "Position",[1 1 style.exportWidthInches style.convergenceHeightInches], ...
    "Renderer","painters");
convergenceFigure.InvertHardcopy = "off";

convergenceAxes = axes( ...
    convergenceFigure, ...
    "Units","normalized", ...
    "Position",[0.125 0.17 0.84 0.77]);
hold(convergenceAxes,"on");
box(convergenceAxes,"on");
grid(convergenceAxes,"on");

convergenceAxes.Color = style.lightBackground;
convergenceAxes.FontName = style.fontName;
convergenceAxes.FontSize = style.axisFontSize;
convergenceAxes.FontWeight = "normal";
convergenceAxes.XColor = style.lightText;
convergenceAxes.YColor = style.lightText;
convergenceAxes.GridColor = style.lightGrid;
convergenceAxes.GridAlpha = 0.75;
convergenceAxes.LineWidth = 0.8;
convergenceAxes.TickDir = "out";
convergenceAxes.Layer = "top";

bandX = [referenceFe;flipud(referenceFe)];
bandY = [lowerSigma;flipud(upperSigma)];

sigmaHandle = fill( ...
    convergenceAxes,bandX,bandY,style.bandColor, ...
    "EdgeColor","none", ...
    "DisplayName","Mean \\pm 1\\sigma");

runHandle = gobjects(1);
for runIndex = 1:numberOfRuns
    if runIndex == 1
        runHandle = plot( ...
            convergenceAxes,referenceFe,objectiveHistory(:,runIndex), ...
            "Color",style.runColor, ...
            "LineWidth",0.8, ...
            "DisplayName","Independent runs");
    else
        plot( ...
            convergenceAxes,referenceFe,objectiveHistory(:,runIndex), ...
            "Color",style.runColor, ...
            "LineWidth",0.8, ...
            "HandleVisibility","off");
    end
end

meanHandle = plot( ...
    convergenceAxes,referenceFe,meanObjective, ...
    "Color",style.meanColor, ...
    "LineWidth",2.2, ...
    "DisplayName","Mean best-so-far");

scatter( ...
    convergenceAxes,referenceFe(end),meanObjective(end),34,"o", ...
    "MarkerFaceColor",style.meanColor, ...
    "MarkerEdgeColor",style.lightBackground, ...
    "LineWidth",0.8, ...
    "HandleVisibility","off");

xlabel(convergenceAxes,"Function Evaluations", ...
    "Color",style.lightText, ...
    "FontName",style.fontName, ...
    "FontSize",style.labelFontSize, ...
    "FontWeight","normal");
ylabel(convergenceAxes,"Best Objective, J", ...
    "Color",style.lightText, ...
    "FontName",style.fontName, ...
    "FontSize",style.labelFontSize, ...
    "FontWeight","normal");

xlim(convergenceAxes,[0 referenceFe(end)]);
xticks(convergenceAxes,unique([0:200:referenceFe(end) referenceFe(end)]));

yAll = [objectiveHistory(:);lowerSigma;upperSigma];
yRange = max(yAll)-min(yAll);
if yRange <= 0
    yRange = max(1,abs(mean(yAll)))*0.05;
end
ylim(convergenceAxes,[min(yAll)-0.08*yRange max(yAll)+0.10*yRange]);

finalText = sprintf("Final mean = %.4g \\pm %.3g", ...
    meanObjective(end),stdObjective(end));
text( ...
    convergenceAxes, ...
    0.98*referenceFe(end), ...
    meanObjective(end), ...
    finalText, ...
    "Interpreter","tex", ...
    "FontName",style.fontName, ...
