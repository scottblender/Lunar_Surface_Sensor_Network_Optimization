function report = checkDemCompatibility(model,latitudesRad,longitudesRad,requirements)
% CHECKDEMCOMPATIBILITY - Reject unsupported native coverage or coarse source spacing.
% Requirements: candidateSpacingKm; optional maximumDemSpacingMeters (defaults to
% candidate spacing), terrainRangeKm, terrainRangeStepKm, azimuthStepRad, moonRadiusKm.
% Physical spacing is conservatively evaluated over the required terrain footprint.
arguments
    model (1,1) struct
    latitudesRad (:,1) double
    longitudesRad (:,1) double
    requirements (1,1) struct
end
defaults = struct("moonRadiusKm",1737.4,"terrainRangeKm",100, ...
    "terrainRangeStepKm",0.5,"azimuthStepRad",deg2rad(0.1), ...
    "candidateSpacingKm",15,"maximumDemSpacingMeters",[]);
settings = utilities.overrideConfig(defaults,requirements);
assert(isfield(model,"nativeGrid"),"checkDemCompatibility:MissingNativeGrid", ...
    "DEM has no original grid metadata; reload it with the current loader.");
grid = model.nativeGrid;
assert(~isempty(latitudesRad) && numel(latitudesRad)==numel(longitudesRad) && ...
    all(isfinite(latitudesRad)) && all(abs(latitudesRad)<=pi/2) && ...
    all(isfinite(longitudesRad)),"checkDemCompatibility:Candidates","Invalid candidate coordinates.");
validateattributes(settings.moonRadiusKm,{'numeric'},{'scalar','positive','finite'});
validateattributes(settings.terrainRangeKm,{'numeric'},{'scalar','nonnegative','finite','<',pi*settings.moonRadiusKm/2});
validateattributes(settings.terrainRangeStepKm,{'numeric'},{'scalar','positive','finite'});
validateattributes(settings.azimuthStepRad,{'numeric'},{'scalar','positive','finite'});
validateattributes(settings.candidateSpacingKm,{'numeric'},{'scalar','positive','finite'});
if isempty(settings.maximumDemSpacingMeters)
    settings.maximumDemSpacingMeters = 1000*settings.candidateSpacingKm;
end
validateattributes(settings.maximumDemSpacingMeters,{'numeric'},{'scalar','positive','finite'});
alpha = settings.terrainRangeKm/settings.moonRadiusKm;
south = max(-pi/2,latitudesRad-alpha);
north = min(pi/2,latitudesRad+alpha);
requiredLatitude = [min(south) max(north)];
assert(requiredLatitude(1)>=grid.latitudeCoverageRad(1)-1e-10 && ...
    requiredLatitude(2)<=grid.latitudeCoverageRad(2)+1e-10, ...
    "checkDemCompatibility:LatitudeCoverage", ...
    "Native DEM covers %.6f to %.6f deg latitude; candidates plus %.1f km terrain margin need %.6f to %.6f deg.", ...
    rad2deg(grid.latitudeCoverageRad(1)),rad2deg(grid.latitudeCoverageRad(2)), ...
    settings.terrainRangeKm,rad2deg(requiredLatitude(1)),rad2deg(requiredLatitude(2)));
if ~grid.fullLongitude
    touchesPole = abs(latitudesRad)+alpha >= pi/2-1e-12;
    assert(~any(touchesPole),"checkDemCompatibility:LongitudeCoverage", ...
        "Terrain search reaches a pole and needs full longitude coverage; this DEM is regional.");
    halfWidth = asin(min(1,sin(alpha)./cos(latitudesRad)));
    offsets = mod(longitudesRad-grid.longitudeStartRad,2*pi);
    assert(all(offsets-halfWidth >= -1e-10 & offsets+halfWidth<=grid.longitudeSpanRad+1e-10), ...
        "checkDemCompatibility:LongitudeCoverage", ...
        "Native longitude footprint does not contain every candidate and its %.1f km terrain search margin.", ...
        settings.terrainRangeKm);
end
% Largest north/south gap and largest east/west gap at the most equatorward
% required latitude. Padding never contributes to these native spacing values.
if requiredLatitude(1)<=0 && requiredLatitude(2)>=0
    closestToEquator = 0;
else
    closestToEquator = min(abs(requiredLatitude));
end
northSouthMeters = settings.moonRadiusKm*1000*grid.maximumLatitudeStepRad;
eastWestMeters = settings.moonRadiusKm*1000*cos(closestToEquator)*grid.maximumLongitudeStepRad;
worstMeters = max(northSouthMeters,eastWestMeters);
assert(worstMeters <= settings.maximumDemSpacingMeters*(1+1e-10), ...
    "checkDemCompatibility:ResolutionTooCoarse", ...
    "Native DEM spacing is up to %.1f m N/S and %.1f m E/W over this footprint; " + ...
     "the allowed maximum is %.1f m. Interpolation does not improve native resolution. " + ...
     "Use a finer DEM or explicitly set a justified maximumDemSpacingMeters.", ...
    northSouthMeters,eastWestMeters,settings.maximumDemSpacingMeters);
report = struct("requiredLatitudeDeg",rad2deg(requiredLatitude), ...
    "nativeLatitudeCoverageDeg",rad2deg(grid.latitudeCoverageRad), ...
    "nativeNorthSouthSpacingMeters",northSouthMeters, ...
    "nativeMaximumEastWestSpacingMeters",eastWestMeters, ...
    "maximumAllowedSpacingMeters",settings.maximumDemSpacingMeters, ...
    "candidateSpacingMeters",1000*settings.candidateSpacingKm, ...
    "terrainRadialSpacingMeters",1000*settings.terrainRangeStepKm, ...
    "terrainOuterAzimuthSpacingMeters",1000*settings.terrainRangeKm*settings.azimuthStepRad, ...
    "terrainRadialOversamplingFactor",worstMeters/(1000*settings.terrainRangeStepKm), ...
    "coverageBasis",grid.coverageBasis,"passed",true,"flatnessCertified",false);
if grid.coverageBasis == "legacy_declared_global_2_to_1_raster"
    fprintf("Coverage uses the legacy global 2:1 raster convention; cropped numeric rasters are unsupported.\n");
end
fprintf("DEM preflight passed: native spacing <= %.1f m N/S, %.1f m E/W; limit %.1f m.\n", ...
    northSouthMeters,eastWestMeters,settings.maximumDemSpacingMeters);
if report.terrainRadialOversamplingFactor > 1
    fprintf("Terrain radial samples interpolate the source by up to %.2fx; this adds no terrain detail.\n", ...
        report.terrainRadialOversamplingFactor);
end
end
