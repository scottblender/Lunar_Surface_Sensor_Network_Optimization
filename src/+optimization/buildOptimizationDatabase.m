%% =========================================================================
%  Reference IOD pass
%  =========================================================================

function [acquisitionIndices, ...
    bestConsecutiveRunLength, ...
    acceptedEpochsInSearchWindow] = ...
    selectReferenceIodPass( ...
        availability, ...
        times, ...
        searchEndTime, ...
        desiredCount)

availability = ...
    logical(availability(:).');

iodWindowMask = ...
    (times <= searchEndTime).';

eligible = ...
    availability & ...
    iodWindowMask;

acceptedEpochsInSearchWindow = ...
    nnz(eligible);

changes = ...
    diff([false,eligible,false]);

runStarts = ...
    find(changes == 1);

runEnds = ...
    find(changes == -1)-1;

bestRun = ...
    zeros(0,1);

for runIndex = 1:length(runStarts)

    currentRun = ...
        ( ...
        runStarts(runIndex): ...
        runEnds(runIndex) ...
        ).';

    if length(currentRun) > length(bestRun)

        bestRun = ...
            currentRun;
    end
end

bestConsecutiveRunLength = ...
    length(bestRun);

if bestConsecutiveRunLength < desiredCount

    acquisitionIndices = ...
        zeros(0,1);

    return
end

selectionLocations = ...
    round(linspace( ...
        1, ...
        bestConsecutiveRunLength, ...
        desiredCount));

acquisitionIndices = ...
    bestRun(selectionLocations);

acquisitionIndices = ...
    acquisitionIndices(:);

assert(length(acquisitionIndices) == desiredCount, ...
    "IOD acquisition selection returned the wrong number of observations.");

assert(length(unique(acquisitionIndices)) == desiredCount, ...
    "IOD acquisition selection contains duplicate epochs.");

end

%% =========================================================================
%  Simulate fixed IOD measurements
%  =========================================================================

function [observerPositionsMci,rightAscension,declination] = ...
    simulateSingleSensorMeasurements( ...
        times, ...
        truthStateHistory, ...
        sensorLatitude, ...
        sensorLongitude, ...
        dem, ...
        measurementAvailable, ...
        measurementNoiseFactor, ...
        measurementNoiseSeed, ...
        moonRadius, ...
        theta0, ...
        angularRate)

numberOfTimes = ...
    length(times);

observerPositionsMci = ...
    zeros(numberOfTimes,3);

rightAscension = ...
    NaN(numberOfTimes,1);

declination = ...
    NaN(numberOfTimes,1);

sensorMoonRotatingState = ...
    referenceFrames.topographic( ...
        zeros(6,1), ...
        sensorLatitude, ...
        sensorLongitude, ...
        dem, ...
        moonRadius, ...
        "toRotating");

noiseStream = ...
    RandStream( ...
        'mt19937ar', ...
        'Seed',measurementNoiseSeed);

for timeIndex = 1:numberOfTimes

    observationTime = ...
        times(timeIndex);

    sensorMciState = ...
        referenceFrames.moonRotating( ...
            sensorMoonRotatingState, ...
            observationTime, ...
            theta0, ...
            angularRate, ...
            "toInertial");

    observerPositionsMci(timeIndex,:) = ...
        sensorMciState(1:3).';

    if ~measurementAvailable(timeIndex)
        continue
    end

    idealMeasurement = ...
        measurements.surfaceRaDecMeasurement( ...
            truthStateHistory(:,timeIndex), ...
            observationTime, ...
            sensorLatitude, ...
            sensorLongitude, ...
            dem, ...
            moonRadius, ...
            theta0, ...
            angularRate);

    noisyMeasurement = ...
        idealMeasurement + ...
        measurementNoiseFactor* ...
        randn(noiseStream,2,1);

    rightAscension(timeIndex) = ...
        wrapAngle(noisyMeasurement(1));

    declination(timeIndex) = ...
        noisyMeasurement(2);
end

end

%% =========================================================================
%  Reference orbital state
%  =========================================================================

function state = ...
    referenceOrbitState( ...
        periapsisAltitudeKm, ...
        eccentricity, ...
        inclination, ...
        raan, ...
        argumentOfPeriapsis, ...
        trueAnomaly, ...
        moonRadius, ...
        moonMu)

periapsisRadius = ...
    moonRadius + periapsisAltitudeKm;

semiMajorAxis = ...
    periapsisRadius/(1-eccentricity);

semilatusRectum = ...
    semiMajorAxis*(1-eccentricity^2);

radius = ...
    semilatusRectum / ...
    (1+eccentricity*cos(trueAnomaly));

positionPerifocal = ...
    radius*[ ...
        cos(trueAnomaly)
        sin(trueAnomaly)
        0
    ];

velocityPerifocal = ...
    sqrt(moonMu/semilatusRectum)*[ ...
        -sin(trueAnomaly)
         eccentricity+cos(trueAnomaly)
         0
    ];

rotationRaan = [ ...
     cos(raan),-sin(raan),0
     sin(raan), cos(raan),0
     0,0,1
];

rotationInclination = [ ...
    1,0,0
    0,cos(inclination),-sin(inclination)
    0,sin(inclination), cos(inclination)
];

rotationPeriapsis = [ ...
     cos(argumentOfPeriapsis),-sin(argumentOfPeriapsis),0
     sin(argumentOfPeriapsis), cos(argumentOfPeriapsis),0
     0,0,1
];

perifocalToMci = ...
    rotationRaan * ...
    rotationInclination * ...
    rotationPeriapsis;

state = [ ...
    perifocalToMci*positionPerifocal
    perifocalToMci*velocityPerifocal
];

end

%% =========================================================================
%  Generic Earth / Sun histories
%  =========================================================================

function [earthPositionsMci,sunPositionsMci] = ...
    buildCelestialHistories( ...
        times, ...
        moonAngularRate, ...
        ephemeris)

numberOfTimes = ...
    length(times);

earthPhase = ...
    ephemeris.earthPhase0Rad + ...
    moonAngularRate*times.';

earthPositionsMci = ...
    ephemeris.earthMoonDistanceKm*[ ...
        cos(earthPhase)
        sin(earthPhase)
        zeros(1,numberOfTimes)
    ];

sunRate = ...
    2*pi/ephemeris.sunOrbitalPeriodSeconds;

sunPhase = ...
    ephemeris.sunPhase0Rad + ...
    sunRate*times.';

sunPlanarPositions = ...
    ephemeris.sunMoonDistanceKm*[ ...
        cos(sunPhase)
        sin(sunPhase)
        zeros(1,numberOfTimes)
    ];

solarInclination = ...
    ephemeris.solarInclinationRad;

solarRotation = [ ...
    1,0,0
    0,cos(solarInclination),-sin(solarInclination)
    0,sin(solarInclination), cos(solarInclination)
];

sunPositionsMci = ...
    solarRotation*sunPlanarPositions;

end

