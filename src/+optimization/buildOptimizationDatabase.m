%% =========================================================================
%  Fixed-P0 IOD calibration
%  =========================================================================

function [fixedInitialCovariance,calibration] = ...
    buildFixedIodPrior( ...
        dem, ...
        measurementCovariance, ...
        config, ...
        moonRadius, ...
        moonMu, ...
        theta0, ...
        moonAngularRate)
% BUILDFIXEDIODPRIOR
% Estimate one fixed P0 from one independent reference IOD acquisition.
%
% The IOD time grid is independent of the optimization tracking time grid.
% The resulting covariance is reused identically for every RSO and every
% network optimization.

%% ========================================================================
%  Independent IOD time grid
%  ========================================================================

iodTimes = ...
    ( ...
    0: ...
    config.iod.outputStepSeconds: ...
    config.tracking.finalTimeSeconds ...
    ).';

if iodTimes(end) < config.tracking.finalTimeSeconds

    iodTimes(end+1,1) = ...
        config.tracking.finalTimeSeconds;
end

numberOfIodTimes = ...
    length(iodTimes);

%% ========================================================================
%  Celestial histories on IOD time grid
%  ========================================================================

[iodEarthPositionsMci,iodSunPositionsMci] = ...
    buildCelestialHistories( ...
        iodTimes, ...
        moonAngularRate, ...
        config.ephemeris);

%% ========================================================================
%  Reference orbit
%  ========================================================================

if isempty(config.iod.referenceInitialStateMoonInertial)

    referenceInitialState = ...
        referenceOrbitState( ...
            config.iod.referencePeriapsisAltitudeKm, ...
            config.iod.referenceEccentricity, ...
            config.iod.referenceInclinationRad, ...
            config.iod.referenceRaanRad, ...
            config.iod.referenceArgumentOfPeriapsisRad, ...
            config.iod.referenceTrueAnomalyRad, ...
            moonRadius, ...
            moonMu);

else

    referenceInitialState = ...
        config.iod.referenceInitialStateMoonInertial;
end

[referenceTimes,referenceStates] = ...
    orbitDynamics.propagateLunarOrbit( ...
        referenceInitialState, ...
        iodTimes, ...
        moonMu=moonMu);

assert(max(abs(referenceTimes-iodTimes)) < 1e-9, ...
    "Reference IOD trajectory time grid changed.");

referenceStateHistory = ...
    reshape( ...
        referenceStates.', ...
        6,numberOfIodTimes,1);

%% ========================================================================
%  Fixed reference sensor
%  ========================================================================

referenceSensorLatitude = ...
    config.iod.referenceSensorLatitudeRad;

referenceSensorLongitude = ...
    mod( ...
        config.iod.referenceSensorLongitudeRad, ...
        2*pi);

[referenceHorizonAzimuths, ...
    referenceMaximumTerrainElevation] = ...
    digitalElevationModel.buildMaximumTerrainHorizonDatabase( ...
        referenceSensorLatitude, ...
        referenceSensorLongitude, ...
        dem, ...
        config.terrain.maximumRangeKm, ...
        config.terrain.rangeStepKm, ...
        config.terrain.horizonAzimuthStepRad, ...
        moonRadius);

%% ========================================================================
%  Fully filtered reference visibility
%  ========================================================================

[referenceAvailability,referenceVisibilityDiagnostics] = ...
    optimization.buildFilteredVisibilityDatabase( ...
        iodTimes, ...
        referenceStateHistory, ...
        referenceSensorLatitude, ...
        referenceSensorLongitude, ...
        dem, ...
        referenceHorizonAzimuths, ...
        referenceMaximumTerrainElevation, ...
        iodEarthPositionsMci, ...
        iodSunPositionsMci, ...
        config.visibility.minimumElevationRad, ...
        config.terrain.horizonMarginRad, ...
        config.visibility.earthRadiusKm, ...
        config.visibility.sunRadiusKm, ...
        config.visibility.minimumAngularSeparationRad, ...
        moonRadius, ...
        theta0, ...
        moonAngularRate);

referenceAvailability = ...
    reshape( ...
        referenceAvailability, ...
        1,numberOfIodTimes);

%% ========================================================================
%  Select required acquisition pass
%  ========================================================================

iodSearchEndTime = ...
    iodTimes(1) + ...
    config.iod.searchEndFraction* ...
    (iodTimes(end)-iodTimes(1));

[acquisitionIndices, ...
    bestConsecutiveRunLength, ...
    acceptedEpochsInSearchWindow] = ...
    selectReferenceIodPass( ...
        referenceAvailability, ...
        iodTimes, ...
        iodSearchEndTime, ...
        config.iod.desiredObservationCount);

if bestConsecutiveRunLength < ...
        config.iod.desiredObservationCount

    errorMessage = ...
        "Reference IOD calibration requires %d fully filtered " + ...
        "observations from one continuous pass. The longest pass " + ...
        "before %.3f hr contains only %d epochs at the %.1f s IOD " + ...
        "cadence. Accepted epochs in the full search window = %d.";

    error( ...
        "buildOptimizationDatabase:InsufficientReferenceIodVisibility", ...
        errorMessage, ...
        config.iod.desiredObservationCount, ...
        iodSearchEndTime/3600, ...
        bestConsecutiveRunLength, ...
        config.iod.outputStepSeconds, ...
        acceptedEpochsInSearchWindow);
end

assert( ...
    length(acquisitionIndices) == ...
    config.iod.desiredObservationCount, ...
    "Reference IOD did not return exactly the requested observations.");

%% ========================================================================
%  Simulate fixed noisy reference measurements
%  ========================================================================

measurementNoiseFactor = ...
    chol( ...
        measurementCovariance, ...
        "lower");

[observerPositionsMci, ...
    rightAscension, ...
    declination] = ...
    simulateSingleSensorMeasurements( ...
        iodTimes, ...
        referenceStateHistory(:,:,1), ...
        referenceSensorLatitude, ...
        referenceSensorLongitude, ...
        dem, ...
        referenceAvailability.', ...
        measurementNoiseFactor, ...
        config.iod.measurementNoiseSeedBase, ...
        moonRadius, ...
        theta0, ...
        moonAngularRate);

%% ========================================================================
%  One Monte Carlo IOD
%  ========================================================================

[iodState, ...
    fixedInitialCovariance, ...
    iodReferenceTime, ...
    iodDiagnostics] = ...
    iod.anglesOnlyIod( ...
        iodTimes, ...
        rightAscension, ...
        declination, ...
