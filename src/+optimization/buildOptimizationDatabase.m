%% =========================================================================
%  Recursive configuration merge
%  =========================================================================

function output = ...
    mergeStruct(defaults,override)

output = ...
    defaults;

overrideFields = ...
    fieldnames(override);

for fieldIndex = 1:length(overrideFields)

    fieldName = ...
        overrideFields{fieldIndex};

    overrideValue = ...
        override.(fieldName);

    if isfield(output,fieldName) && ...
            isstruct(output.(fieldName)) && ...
            isscalar(output.(fieldName)) && ...
            isstruct(overrideValue) && ...
            isscalar(overrideValue)

        output.(fieldName) = ...
            mergeStruct( ...
                output.(fieldName), ...
                overrideValue);

    else

        output.(fieldName) = ...
            overrideValue;
    end
end

end

